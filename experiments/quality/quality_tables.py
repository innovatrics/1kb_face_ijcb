r"""Quality-matrix and budget-sweep tables from the per-cell quality medians (CPU).

Reads ``<input-root>/quality/quality_{colorferet,kk}.csv`` (``measure_quality.py``;
``--from-results`` reads the shipped paper results) and writes into ``--out-dir``
(default ``$FACE1KB_OUTPUT_ROOT/tables``):

* ``quality_matrix.tex`` (tab:quality-matrix) -- Color FERET medians of PSNR, SSIM,
  MS-SSIM, LPIPS and DISTS at 1024 B for 112 and 224 px, one block per resolution,
  codecs sorted by SSIM. Per column and block the best value is shaded green and
  the worst red (LPIPS and DISTS: lower is better). A codec measured on fewer than
  half of the block's median crop count (the 300-crop CompressAI subset) is marked
  ``$^{\ddagger}$`` and does not compete for the shading.
* ``budget_sweep.tex`` (tab:budget-sweep) -- WebP and Ours-ACCURATE at 1024 and
  512 B, 112 px, both datasets: PSNR, SSIM, LPIPS and the crop count.

Examples
--------
    python experiments/quality/quality_tables.py --from-results
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

from face1kb import config
from face1kb.data.cli_utils import setup_logging
from face1kb.report import latex

log = logging.getLogger("quality.tables")

#: Codec roster of the quality matrix (codec, label).
MATRIX_CODECS = (
    ("jpeg_ai", "JPEG-AI"),
    ("ours_accurate", "Ours-ACCURATE"),
    ("ours_fast", "Ours-FAST"),
    ("avif", "AVIF"),
    ("webp", "WebP"),
    ("jpeg_xl", "JPEG~XL"),
    ("heif", "HEIF"),
    ("jpeg_fzt", "JPEG-FzT"),
    ("neural_mbt2018_mean", "mbt2018"),
    ("neural_bmshj2018", "bmshj2018"),
    ("jpeg", "JPEG"),
    ("jpeg2000", "JPEG~2000"),
)
#: Resolution blocks of the quality matrix.
MATRIX_RESOLUTIONS = (112, 224)
#: (column, format, higher is better).
MATRIX_METRICS = (
    ("psnr", "%.2f", True),
    ("ssim", "%.3f", True),
    ("ms_ssim", "%.3f", True),
    ("lpips", "%.3f", False),
    ("dists", "%.3f", False),
)
#: A codec below this share of the block's median crop count does not compete.
SUPPORT_FRACTION = 0.5
#: Budget-sweep blocks (dataset, label), codecs (codec, label) and budgets.
SWEEP_DATASETS = (("kk", "AI-Solutions-KK"), ("colorferet", "Color~FERET"))
SWEEP_CODECS = (("webp", "WebP"), ("ours_accurate", "Ours-ACCURATE"))
SWEEP_BUDGETS = (1024, 512)
SWEEP_RES = 112
#: First comment line of the generated tables and of the published copies.
HEADER = "% generated by experiments/quality/quality_tables.py"
PAPER_HEADERS = {
    "quality_matrix": "% generated by generate_quality_matrix.py",
    "budget_sweep": "% generated by generate_quality_matrix.py (write_budget_sweep)",
}


def low_support(rows: list[tuple[str, dict]]) -> set[str]:
    """Codecs with fewer than half of the block's median crop count (upper median)."""
    ns = sorted(r["n"] for _c, r in rows)
    floor = ns[len(ns) // 2] * SUPPORT_FRACTION
    return {c for c, r in rows if r["n"] < floor}


def _extremes(rows, key: str, higher_better: bool):
    """(best, worst) codec of one column over the well-supported rows."""
    weak = low_support(rows)
    vals = [(c, r[key]) for c, r in rows if c not in weak]
    if len(vals) < 2:
        return None, None
    best = (max if higher_better else min)(vals, key=lambda x: x[1])[0]
    worst = (min if higher_better else max)(vals, key=lambda x: x[1])[0]
    return best, worst


def quality_matrix(df, budget: int = 1024, header: str = HEADER) -> str:
    """Render the quality matrix of one dataset's quality frame."""
    df = df[df.budget == budget]
    ncol = 2 + len(MATRIX_METRICS)
    lines = [
        header,
        "\\begin{tabular}{ll" + "r" * len(MATRIX_METRICS) + "}",
        "\\toprule",
        "Codec & Res. & PSNR & SSIM & MS-SSIM & LPIPS & DISTS \\\\",
        "\\midrule",
    ]
    label = dict(MATRIX_CODECS)
    for res in MATRIX_RESOLUTIONS:
        sub = df[df.res == res]
        rowmap = {r["codec"]: r for r in sub.to_dict("records")}
        present = [(c, rowmap[c]) for c, _ in MATRIX_CODECS if c in rowmap]
        present.sort(key=lambda cr: cr[1].get("ssim", 0), reverse=True)
        shades = {k: _extremes(present, k, hb) for k, _f, hb in MATRIX_METRICS}
        weak = low_support(present)
        lines.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\textit{{{res}\\,px}}}} \\\\")
        for c, r in present:
            cells = []
            for key, fmt, _hb in MATRIX_METRICS:
                best, worst = shades[key]
                s = fmt % r[key]
                if c == best:
                    s = latex.shade_best(s, emphasis=False)
                elif c == worst:
                    s = latex.shade_worst(s, emphasis=False)
                cells.append(s)
            mark = "$^{\\ddagger}$" if c in weak else ""
            lines.append(f"{label[c]}{mark} & {res} & " + " & ".join(cells) + " \\\\")
        if res != MATRIX_RESOLUTIONS[-1]:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return latex.finalize_table("quality_matrix", "\n".join(lines) + "\n")


def budget_sweep(frames: dict, header: str = HEADER) -> str:
    """Render the 1024 -> 512 B sweep (``frames``: dataset -> quality frame)."""
    lines = [
        header,
        "\\begin{tabular}{lllrrrr}",
        "\\toprule",
        "Dataset & Codec & Budget & PSNR & SSIM & LPIPS & $n$ \\\\",
        "\\midrule",
    ]
    for di, (ds, label) in enumerate(SWEEP_DATASETS):
        df = frames[ds]
        df = df[df.res == SWEEP_RES]
        for codec, disp in SWEEP_CODECS:
            for budget in SWEEP_BUDGETS:
                sub = df[(df.codec == codec) & (df.budget == budget)]
                if sub.empty:
                    continue
                r = sub.iloc[0]
                lines.append(
                    f"{label} & {disp} & {budget} & {r.psnr:.2f} & "
                    f"{r.ssim:.3f} & {r.lpips:.3f} & {int(r.n):,} \\\\"
                )
        if di != len(SWEEP_DATASETS) - 1:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write quality_matrix.tex and budget_sweep.tex."""
    import pandas as pd  # noqa: PLC0415

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument(
        "--input-root",
        type=Path,
        default=None,
        help="folder holding quality/ (default: $FACE1KB_OUTPUT_ROOT)",
    )
    src.add_argument("--from-results", action="store_true", help="read <repo>/results")
    ap.add_argument("--matrix-dataset", default="colorferet", choices=config.DATASETS)
    ap.add_argument(
        "--paper-header",
        action="store_true",
        help="write the first comment line of the published tables",
    )
    ap.add_argument("--out-dir", type=Path, default=None)
    args = ap.parse_args(argv)
    setup_logging()

    base = config.RESULTS_ROOT if args.from_results else args.input_root
    qdir = (base or config.OUTPUT_ROOT) / "quality"
    frames = {ds: pd.read_csv(qdir / f"quality_{ds}.csv") for ds in config.DATASETS}
    out_dir = args.out_dir or config.output_dir("tables")
    out_dir.mkdir(parents=True, exist_ok=True)

    def hdr(stem):
        return PAPER_HEADERS[stem] if args.paper_header else HEADER

    for name, tex in (
        (
            "quality_matrix",
            quality_matrix(frames[args.matrix_dataset], header=hdr("quality_matrix")),
        ),
        ("budget_sweep", budget_sweep(frames, header=hdr("budget_sweep"))),
    ):
        (out_dir / f"{name}.tex").write_text(tex)
        log.info("wrote %s", out_dir / f"{name}.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
