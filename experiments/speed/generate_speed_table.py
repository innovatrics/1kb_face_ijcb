r"""Speed table (``tab:speed``) and speed-vs-resolution figure (``fig:speed-trend``).

Reads the speed CSVs of ``benchmark_speed.py`` and ``benchmark_jpegai_speed.py``
from ``<input-root>/quality/`` in this order (the first row matching a
``(codec, device, res, budget)`` key wins):

    speed_cpu_classical.csv, speed_gpu_learned.csv, speed_cpu_learned.csv,
    speed_cpu_jpegai.csv, speed_gpu_jpegai.csv

and writes

* ``OUTPUT_ROOT/tables/speed_benchmark.tex``: median encode / decode ms of every
  codec at 112 px under a 1024 B request, on one CPU core and on one GPU, each
  device group with the realised median size of the timed streams. Per timing
  column the fastest cell is shaded best and the slowest worst (columns with fewer
  than two values are not shaded); the size columns are not ranked.
* ``OUTPUT_ROOT/figures/speed_trend.png``: median encode and decode time versus
  resolution at 1024 B (log scale; solid CPU, dashed GPU; series with at least two
  resolutions).

``--from-results`` reads the shipped ``results/quality`` CSVs, which reproduces the
published table.

Example
-------
    python experiments/speed/generate_speed_table.py --from-results
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config
from face1kb.report import latex, style

log = logging.getLogger("speed_table")

#: Input CSVs in lookup order.
CSVS = (
    "speed_cpu_classical.csv",
    "speed_gpu_learned.csv",
    "speed_cpu_learned.csv",
    "speed_cpu_jpegai.csv",
    "speed_gpu_jpegai.csv",
)
#: Codecs in table order.
ORDER = (
    "jpeg",
    "jpeg2000",
    "webp",
    "jpeg_xl",
    "avif",
    "heif",
    "jpeg_fzt",
    "jpeg_ai",
    "neural_bmshj2018",
    "neural_mbt2018_mean",
    "ours_fast",
    "ours_accurate",
)
NAME = style.CODEC_LABELS
#: (device, column, ranked) of the table columns.
COLUMNS = (
    ("cpu", "median_bytes", False),
    ("cpu", "enc_median_ms", True),
    ("cpu", "dec_median_ms", True),
    ("gpu", "median_bytes", False),
    ("gpu", "enc_median_ms", True),
    ("gpu", "dec_median_ms", True),
)
STEM = "speed_benchmark"


def load(root: Path) -> pd.DataFrame:
    """Concatenate the speed CSVs under ``root/quality`` (missing files skipped)."""
    frames = [
        pd.read_csv(root / "quality" / c)
        for c in CSVS
        if (root / "quality" / c).exists()
    ]
    if not frames:
        raise SystemExit(f"no speed CSVs under {root / 'quality'}")
    df = pd.concat(frames, ignore_index=True)
    for col in ("res", "budget"):
        df[col] = df[col].astype(int)
    return df


def cell(df, codec, dev, res, budget, col):
    """Value of the first matching row, or None if absent / empty."""
    r = df[
        (df.codec == codec)
        & (df.device == dev)
        & (df.res == res)
        & (df.budget == budget)
    ]
    if r.empty or pd.isna(r.iloc[0][col]):
        return None
    return float(r.iloc[0][col])


def fmt_ms(v) -> str:
    """Milliseconds with 3 significant digits in the ranges of the table."""
    if v is None:
        return "--"
    if v >= 100:
        return f"{v:.0f}"
    if v >= 10:
        return f"{v:.1f}"
    return f"{v:.2f}"


def fmt_bytes(v) -> str:
    """Realised median size in whole bytes."""
    return "--" if v is None else f"{v:.0f}"


def speed_table(df: pd.DataFrame, res: int = 112, budget: int = 1024) -> str:
    """Colour-only LaTeX table (see the module docstring)."""
    present = set(df.codec)
    codecs = [c for c in ORDER if c in present]
    grid = {
        c: [cell(df, c, dev, res, budget, m) for dev, m, _ in COLUMNS] for c in codecs
    }
    best, worst = [], []
    for j, (_, _, ranked) in enumerate(COLUMNS):
        vv = [grid[c][j] for c in codecs if grid[c][j] is not None] if ranked else []
        best.append(min(vv) if len(vv) > 1 else None)
        worst.append(max(vv) if len(vv) > 1 else None)

    def shade(v, j):
        txt = fmt_ms(v) if COLUMNS[j][2] else fmt_bytes(v)
        if v is None:
            return txt
        if best[j] is not None and v == best[j]:
            return latex.shade_best(txt, emphasis=False)
        if worst[j] is not None and v == worst[j]:
            return latex.shade_worst(txt, emphasis=False)
        return txt

    lines = [
        "% generated by generate_speed_table.py",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        "& \\multicolumn{3}{c}{CPU (1 core)} & \\multicolumn{3}{c}{GPU} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
        "Codec & B & enc.\\,ms & dec.\\,ms & B & enc.\\,ms & dec.\\,ms \\\\",
        "\\midrule",
    ]
    for c in codecs:
        cells = " & ".join(shade(grid[c][j], j) for j in range(len(COLUMNS)))
        lines.append(f"{NAME[c]} & {cells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def write_figure(df: pd.DataFrame, path: Path, budget: int = 1024) -> None:
    """Median encode / decode ms versus resolution per codec and device (log y)."""
    import matplotlib.pyplot as plt  # noqa: PLC0415

    reses = sorted(set(df.res))
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.2))
    for ax, (metric, title) in zip(
        axes, [("enc_median_ms", "Encode"), ("dec_median_ms", "Decode")]
    ):
        for c in [c for c in ORDER if c in set(df.codec)]:
            for dev, ls in (("cpu", "-"), ("gpu", "--")):
                ys = [cell(df, c, dev, r, budget, metric) for r in reses]
                pts = [(r, y) for r, y in zip(reses, ys) if y is not None]
                if len(pts) < 2:
                    continue
                xs, yy = zip(*pts)
                ax.plot(
                    xs, yy, ls, marker="o", ms=3, lw=1.3, label=f"{NAME[c]} ({dev})"
                )
        ax.set_yscale("log")
        ax.set_xlabel("resolution (px)")
        ax.set_ylabel("median time (ms, log)")
        ax.set_title(f"{title} time vs resolution ({budget} B)")
        ax.grid(True, which="both", alpha=0.25)
    axes[1].legend(fontsize=6, ncol=2, loc="upper left")
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=style.FIGURE_DPI["speed"], bbox_inches="tight")
    plt.close(fig)
    log.info("wrote %s", path)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--from-results", action="store_true", help="read results/")
    ap.add_argument("--input-root", default=None, help="root holding quality/*.csv")
    ap.add_argument("--output-root", default=None, help="override FACE1KB_OUTPUT_ROOT")
    ap.add_argument("--no-figure", action="store_true")
    args = ap.parse_args(argv)
    logging.basicConfig(
        level=logging.INFO, format="%(levelname)s %(name)s: %(message)s"
    )
    style.use_agg()
    in_root = Path(
        args.input_root
        or (config.RESULTS_ROOT if args.from_results else config.OUTPUT_ROOT)
    )
    out_root = Path(args.output_root) if args.output_root else config.OUTPUT_ROOT
    df = load(in_root)
    tab = out_root / "tables" / f"{STEM}.tex"
    tab.parent.mkdir(parents=True, exist_ok=True)
    tab.write_text(latex.finalize_table(STEM, speed_table(df)))
    log.info("wrote %s", tab)
    if not args.no_figure:
        write_figure(df, out_root / "figures" / "speed_trend.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
