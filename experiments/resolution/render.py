r"""Table and figure of the resolution-information analysis (from its CSVs).

Reads ``embedding_decomposition.csv``, ``eer_by_resolution.csv`` and
``spectral_retention.csv`` of ``resolution_information/`` (written by ``analyze.py``)
and writes

* ``tables/res_decomp.tex`` -- the resolution-information decomposition of one
  dataset (default AI-Solutions-KK) for the four anchor matchers: AC spectral energy
  retained vs. 224 px (4 decimals), identity cosine vs. 112 px (3 decimals) and clean
  EER in % (2 decimals) at 64 / 96 / 112 / 168 / 224 px;
* ``figures/resolution_summary.png`` -- the three measurements for every dataset and
  matcher in the CSVs (identity cosine vs. 112 px, spectral energy vs. 224 px, clean
  EER; one shared legend panel).

Only clean ``aligned_<R>`` rows are used. ``--from-results`` reads the shipped paper
aggregates (``results/resolution_information``).

Examples
--------
    python experiments/resolution/render.py
    python experiments/resolution/render.py --from-results --no-figure
"""

from __future__ import annotations

import argparse
import logging
import re
from pathlib import Path

import numpy as np
import pandas as pd

from face1kb import config
from face1kb.data.cli_utils import setup_logging

log = logging.getLogger("resolution_render")

RESOLUTIONS = config.RESOLUTIONS
#: (matcher, row label) of the table.
TABLE_MODELS: tuple[tuple[str, str], ...] = (
    ("arcface_antelopev2", "ArcFace (antelopev2)"),
    ("topofr_r100", "TopoFR (r100)"),
    ("edgeface_xs", "EdgeFace-XS"),
    ("lvface_l", "LVFace-L"),
)
CLEAN_TAG = re.compile(r"^aligned_\d+$")
HEADER = "% generated by experiments/resolution/render.py"


def clean_rows(df: pd.DataFrame) -> pd.DataFrame:
    """Rows of the clean ``aligned_<R>`` sources (no suffix, no stray files)."""
    if df.empty or "tag" not in df.columns:
        return df
    return df[df.tag.astype(str).str.match(CLEAN_TAG)]


def _lookup(df: pd.DataFrame, dataset: str, model: str, res: int, col: str) -> float:
    r = df[(df.dataset == dataset) & (df.model == model) & (df.res == res)]
    return float(r[col].iloc[0]) if len(r) and col in r else float("nan")


def _fmt(v: float, nd: int) -> str:
    return "--" if not np.isfinite(v) else f"{v:.{nd}f}"


def table(
    dec: pd.DataFrame, eer: pd.DataFrame, spec: pd.DataFrame, dataset: str
) -> str:
    """Render the decomposition table of ``dataset`` as a LaTeX tabular."""
    dec, eer = clean_rows(dec), clean_rows(eer)
    cols = " & ".join(str(r) for r in RESOLUTIONS)
    sp = spec[spec.dataset == dataset].set_index("res")["frac_energy_retained"]
    lines = [
        HEADER,
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "& \\multicolumn{5}{c}{Resolution (px)} \\\\",
        "\\cmidrule(lr){2-6}",
        f"Quantity & {cols} \\\\",
        "\\midrule",
        "AC spectral energy retained vs.\\ 224 & "
        + " & ".join(_fmt(float(sp.get(r, np.nan)), 4) for r in RESOLUTIONS)
        + " \\\\",
        "\\midrule",
        "\\multicolumn{6}{l}{\\emph{Identity cosine vs.\\ 112 (per matcher)}} \\\\",
    ]
    for m, lab in TABLE_MODELS:
        vals = [_lookup(dec, dataset, m, r, "resize_cos") for r in RESOLUTIONS]
        lines.append(
            f"\\quad {lab} & " + " & ".join(_fmt(v, 3) for v in vals) + " \\\\"
        )
    lines += [
        "\\midrule",
        "\\multicolumn{6}{l}{\\emph{Clean EER (\\%, per matcher)}} \\\\",
    ]
    for m, lab in TABLE_MODELS:
        vals = [100 * _lookup(eer, dataset, m, r, "eer") for r in RESOLUTIONS]
        lines.append(
            f"\\quad {lab} & " + " & ".join(_fmt(v, 2) for v in vals) + " \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def figure(
    dec: pd.DataFrame, eer: pd.DataFrame, spec: pd.DataFrame, path: Path
) -> None:
    """Identity retention, spectral retention and clean EER vs. resolution."""
    import matplotlib  # noqa: PLC0415

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt  # noqa: PLC0415

    dec, eer = clean_rows(dec), clean_rows(eer)
    fig, ax = plt.subplots(
        1, 4, figsize=(18, 4.5), gridspec_kw={"width_ratios": [1, 1, 1, 0.55]}
    )
    a = dec.dropna(subset=["resize_cos"])
    e = eer.dropna(subset=["eer"]) if not eer.empty else eer
    # one colour per (dataset, model) in both panels, keyed on the union of series
    keys = sorted(
        set(zip(a.dataset, a.model, strict=True))
        | set(zip(e.dataset, e.model, strict=True))
    )
    cycle = plt.rcParams["axes.prop_cycle"].by_key()["color"]
    color = {k: cycle[i % len(cycle)] for i, k in enumerate(keys)}
    for (ds, model), g in a.groupby(["dataset", "model"]):
        g = g.sort_values("res")
        ax[0].plot(
            g.res,
            g.resize_cos,
            marker="o",
            color=color[(ds, model)],
            label=f"{ds}/{model}",
        )
    ax[0].set(
        title="Identity info retained vs 112 (clean)",
        xlabel="resolution",
        ylabel="cos(emb_clean_R, emb_clean_112)",
    )
    ax[0].axhline(1.0, color="k", lw=0.5, ls=":")
    for ds, g in spec.groupby("dataset"):
        g = g.sort_values("res")
        ax[1].plot(g.res, g.frac_energy_retained, marker="s", label=ds)
    ax[1].set(
        title="Raw spectral energy retained vs 224",
        xlabel="resolution",
        ylabel="frac AC spectral energy",
    )
    ax[1].legend(fontsize=7)
    if not eer.empty:
        for (ds, model), g in e.groupby(["dataset", "model"]):
            g = g.sort_values("res")
            ax[2].plot(
                g.res,
                100 * g.eer,
                marker="o",
                color=color[(ds, model)],
                label=f"{ds}/{model}",
            )
    else:
        ax[2].text(0.5, 0.5, "EER not computed", ha="center")
    ax[2].set(title="Clean EER vs resolution", xlabel="resolution", ylabel="EER (%)")
    legend: dict[str, object] = {}
    for axis in (ax[0], ax[2]):
        for h, lab in zip(*axis.get_legend_handles_labels(), strict=True):
            legend.setdefault(lab, h)
    order = [f"{ds}/{m}" for ds, m in keys if f"{ds}/{m}" in legend]
    handles, labels = [legend[k] for k in order], order
    ax[3].axis("off")
    ax[3].legend(handles, labels, loc="center left", fontsize=6.5, frameon=False)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=130, bbox_inches="tight")
    plt.close(fig)


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument(
        "--input-dir", default=None, help="default: OUTPUT_ROOT/resolution_information"
    )
    src.add_argument(
        "--from-results",
        action="store_true",
        help="read the shipped paper results (results/resolution_information)",
    )
    ap.add_argument("--dataset", choices=config.DATASETS, default="kk")
    ap.add_argument("--tables-dir", default=None, help="default: OUTPUT_ROOT/tables")
    ap.add_argument("--figures-dir", default=None, help="default: OUTPUT_ROOT/figures")
    ap.add_argument("--no-figure", action="store_true")
    args = ap.parse_args(argv)
    setup_logging()
    if args.from_results:
        in_dir = config.results_dir("resolution_information")
    elif args.input_dir:
        in_dir = Path(args.input_dir)
    else:
        in_dir = config.output_dir("resolution_information")
    dec = pd.read_csv(in_dir / "embedding_decomposition.csv")
    spec = pd.read_csv(in_dir / "spectral_retention.csv")
    eer_csv = in_dir / "eer_by_resolution.csv"
    eer = pd.read_csv(eer_csv) if eer_csv.exists() else pd.DataFrame()
    tdir = Path(args.tables_dir) if args.tables_dir else config.output_dir("tables")
    tdir.mkdir(parents=True, exist_ok=True)
    (tdir / "res_decomp.tex").write_text(table(dec, eer, spec, args.dataset))
    log.info("wrote %s", tdir / "res_decomp.tex")
    if not args.no_figure:
        fdir = (
            Path(args.figures_dir) if args.figures_dir else config.output_dir("figures")
        )
        figure(dec, eer, spec, fdir / "resolution_summary.png")
        log.info("wrote %s", fdir / "resolution_summary.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
