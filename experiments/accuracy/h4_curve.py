r"""Sub-1 kB budget floor: EER vs byte budget at 112 px (Section 5.5).

Reads ``accuracy/metrics.csv`` (Color FERET, 112 px, clean cells) for the budgets
512, 768, 960 and 1024 B that are present and writes

* ``h4_budget.tex`` (``tab:h4-budget``): ArcFace EER (percent) of the 12 codecs at
  each budget, best / worst per column shaded (bold / underlined) on the printed
  value; a cell with fewer than half of its column's median mated pairs (the
  CompressAI 300-crop subsets at 512 / 1024 B) carries ``$^{\ddagger}$`` and is not
  ranked;
* ``h4_budget_curve.png`` (``fig:h4-curve``): EER vs budget for ArcFace and LVFace-L
  on a log axis, with a 0 % EER drawn at 0.02 %.

Examples
--------
    python experiments/accuracy/h4_curve.py --from-results --paper-header
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config
from face1kb.report.latex import BEST_FILL, WORST_FILL, finalize_table
from face1kb.report.style import use_agg

log = logging.getLogger("h4_curve")

HEADER = "% generated by experiments/accuracy/h4_curve.py"
PAPER_HEADER = "% generated by generate_h4_curve.py"
DATASET, RES = "colorferet", 112
BUDGETS = [512, 768, 960, 1024]
ANCHORS = [("arcface_antelopev2", "ArcFace"), ("lvface_l", "LVFace-L")]
ALL_CODECS = [
    ("jpeg_ai", "JPEG-AI"),
    ("ours_accurate", "Ours-ACCURATE"),
    ("ours_fast", "Ours-FAST"),
    ("avif", "AVIF"),
    ("webp", "WebP"),
    ("jpeg_xl", "JPEG XL"),
    ("heif", "HEIF"),
    ("jpeg_fzt", "JPEG-FzT"),
    ("neural_mbt2018_mean", "mbt2018"),
    ("neural_bmshj2018", "bmshj2018"),
    ("jpeg", "JPEG"),
    ("jpeg2000", "JPEG 2000"),
]
LOW_SUPPORT_FRAC = 0.5
DAGGER = "$^{\\ddagger}$"
#: Zero EERs are drawn at this value on the log axis (percent).
FLOOR = 0.02
FIG_DPI = 130


def _row(df, model, codec, budget):
    """Row of one clean cell with an EER, or None."""
    r = df[
        (df.dataset == DATASET)
        & (df.model == model)
        & (df.res == RES)
        & (df.kind == "compressed")
        & (df.codec == codec)
        & (df.budget == budget)
        & (df.suffix.isna() | (df.suffix == ""))
    ]
    r = r[r.eer.notna()]
    return None if r.empty else r.iloc[0]


def _eer(df, model, codec, budget):
    r = _row(df, model, codec, budget)
    return float(r.eer) * 100 if r is not None else None


def _low_support(df, model, budgets) -> set:
    """``(codec, budget)`` cells below half of their column's median ``n_pos``."""
    weak = set()
    for b in budgets:
        sup = {}
        for c, _ in ALL_CODECS:
            r = _row(df, model, c, b)
            sup[c] = 0.0 if r is None or pd.isna(r.n_pos) else float(r.n_pos)
        seen = [v for v in sup.values() if v > 0]
        ref = float(pd.Series(seen).median()) if seen else 0.0
        weak |= {(c, b) for c, v in sup.items() if 0 < v < LOW_SUPPORT_FRAC * ref}
    return weak


def table(df, budgets, header: str) -> str:
    """Colour-shaded ArcFace EER table."""
    m = ANCHORS[0][0]
    lines = [
        header,
        "\\begin{tabular}{l" + "r" * len(budgets) + "}",
        "\\toprule",
        "Codec (ArcFace, 112\\,px) & "
        + " & ".join(f"{b}\\,B" for b in budgets)
        + " \\\\",
        "\\midrule",
    ]
    mat = {c: [_eer(df, m, c, b) for b in budgets] for c, _ in ALL_CODECS}
    weak = _low_support(df, m, budgets)
    best: list[set] = [set() for _ in budgets]
    worst: list[set] = [set() for _ in budgets]
    for j, b in enumerate(budgets):
        vv = [
            (c, round(mat[c][j], 2))
            for c, _ in ALL_CODECS
            if mat[c][j] is not None and (c, b) not in weak
        ]
        uniq = {v for _, v in vv}
        if len(uniq) >= 2:
            best[j] = {c for c, v in vv if v == min(uniq)}
            worst[j] = {c for c, v in vv if v == max(uniq)}
    for c, clab in ALL_CODECS:
        cells = []
        for j, v in enumerate(mat[c]):
            if v is None:
                cells.append("--")
                continue
            s = f"{v:.2f}"
            if (c, budgets[j]) in weak:
                s = f"{s}{DAGGER}"
            elif c in best[j]:
                s = f"\\cellcolor{{{BEST_FILL}}}{s}"
            elif c in worst[j]:
                s = f"\\cellcolor{{{WORST_FILL}}}{s}"
            cells.append(s)
        lines.append(clab + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def figure(df, budgets, path: Path) -> None:
    """EER vs budget curves for the two anchors."""
    import matplotlib.pyplot as plt  # noqa: PLC0415

    fig, axes = plt.subplots(
        1, len(ANCHORS), figsize=(5.2 * len(ANCHORS), 4), sharey=True
    )
    if len(ANCHORS) == 1:
        axes = [axes]
    style = {
        c: (
            plt.get_cmap("tab20")(i % 20),
            ["-", "--", "-.", ":"][i % 4],
            ["o", "s", "^", "D", "v", "P"][i % 6],
        )
        for i, (c, _) in enumerate(ALL_CODECS)
    }
    for ax, (m, mlab) in zip(axes, ANCHORS):
        for c, clab in ALL_CODECS:
            ys = [_eer(df, m, c, b) for b in budgets]
            pts = [(b, max(y, FLOOR)) for b, y in zip(budgets, ys) if y is not None]
            if len(pts) < 2:
                continue
            xs, yy = zip(*pts)
            col, ls, mk = style[c]
            ax.plot(xs, yy, ls, color=col, marker=mk, ms=4, lw=1.4, label=clab)
        ax.set_ylim(bottom=FLOOR * 0.8)
        ax.axvspan(500, 800, color="#E6A23C", alpha=0.08)
        ax.axvline(800, color="#E6A23C", ls=":", lw=1)
        ax.set_yscale("log")
        ax.set_xlim(left=500)
        ax.set_xlabel("byte budget (B)")
        ax.set_title(f"{mlab} — EER vs budget (112 px)")
        ax.grid(True, which="both", alpha=0.25)
    axes[0].set_ylabel("EER (%, log)")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        fontsize=7.5,
        ncol=6,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.02),
        frameon=False,
    )
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(path, dpi=FIG_DPI, bbox_inches="tight")
    plt.close(fig)


def main(argv: list[str] | None = None) -> int:
    """Write the H4 table and figure."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--input-root", default=None, help="default: outputs/")
    src.add_argument(
        "--from-results", action="store_true", help="read the shipped results/"
    )
    ap.add_argument("--metrics", default=None, help="default: accuracy/metrics.csv")
    ap.add_argument("--out-dir", default=None, help="tables (default outputs/tables)")
    ap.add_argument("--fig-dir", default=None, help="figures (default outputs/figures)")
    ap.add_argument("--no-figures", action="store_true")
    ap.add_argument(
        "--paper-header", action="store_true", help="comment line of the paper"
    )
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    root = (
        config.RESULTS_ROOT
        if args.from_results
        else Path(args.input_root or config.OUTPUT_ROOT)
    )
    df = pd.read_csv(Path(args.metrics or root / "accuracy" / "metrics.csv"))
    df.res = df.res.astype(int)
    df.budget = df.budget.astype(int)
    present = set(df[(df.dataset == DATASET) & (df.res == RES)].budget)
    budgets = [b for b in BUDGETS if b in present]
    log.info("budgets at %d px on %s: %s", RES, DATASET, budgets)
    tab_dir = Path(args.out_dir) if args.out_dir else config.output_dir("tables")
    tab_dir.mkdir(parents=True, exist_ok=True)
    header = PAPER_HEADER if args.paper_header else HEADER
    out = tab_dir / "h4_budget.tex"
    out.write_text(finalize_table("h4_budget", table(df, budgets, header)))
    log.info("wrote %s", out)
    if not args.no_figures:
        use_agg()
        fig_dir = Path(args.fig_dir) if args.fig_dir else config.output_dir("figures")
        fig_dir.mkdir(parents=True, exist_ok=True)
        figure(df, budgets, fig_dir / "h4_budget_curve.png")
        log.info("wrote %s", fig_dir / "h4_budget_curve.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
