r"""LaTeX EER matrices of the recompression study (one per dataset and budget).

Reads ``recompression/recompression_<dataset>_<budget>.csv`` (written by
``recompress.py``) and writes ``tables/recompression_eer_<dataset>_<budget>.tex``:
an 8 x 8 matrix of chain EER (%), rows = source codec, columns = second codec.

Shading: per column (second codec), the best (lowest) and worst (highest) classical
source is shaded green / red, with the bold / underline marker of the paper tables.
The ranking uses the printed (2-decimal) value: every source tied at an extreme is
shaded and a column whose printed values all tie stays unshaded. The Ours-ACCURATE
row and column are never shaded and take no part in the ranking, because the
default matcher (EdgeFace-XS) belongs to the family of the codec's frozen EdgeFace-S
identity anchor. Cells without a CSV row print ``--``.

``--from-results`` renders the shipped paper aggregates (``results/recompression``);
with ``--paper-header`` the first (comment) line is the one of the published tables,
and the output is byte-identical to them.

Examples
--------
    python experiments/recompression/make_tables.py
    python experiments/recompression/make_tables.py --from-results --paper-header
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config
from face1kb.data.cli_utils import setup_logging
from face1kb.report.latex import emphasis_for, shade_best, shade_worst

log = logging.getLogger("recompression_tables")

#: (codec, column label) in matrix order.
CODECS: tuple[tuple[str, str], ...] = (
    ("jpeg", "JPEG"),
    ("jpeg2000", "JPEG\\,2000"),
    ("webp", "WebP"),
    ("jpeg_xl", "JPEG\\,XL"),
    ("avif", "AVIF"),
    ("heif", "HEIF"),
    ("jpeg_fzt", "JPEG-FzT"),
    ("ours_accurate", "Ours-ACC"),
)
#: Codec excluded from shading (EdgeFace-anchored identity side-stream).
CONFOUNDED = "ours_accurate"
#: (dataset, budget) of the four published tables.
CELLS: tuple[tuple[str, int], ...] = (
    ("colorferet", 1024),
    ("kk", 1024),
    ("colorferet", 512),
    ("kk", 512),
)
HEADER = "% generated by experiments/recompression/make_tables.py"
PAPER_HEADER = "% generated by generate_recompression_tables.py"


def table_stem(dataset: str, budget: int) -> str:
    """Stem of the table file of one (dataset, budget)."""
    return f"recompression_eer_{dataset}_{int(budget)}"


def render(df: pd.DataFrame, stem: str, header: str = HEADER) -> str:
    """Render the matrix of one (dataset, budget) CSV as a LaTeX tabular."""
    order = [c for c, _ in CODECS]
    ncol = len(order)
    mat: dict[str, dict[str, float]] = {s: {} for s in order}
    for r in df.itertuples():
        if r.source_codec in mat and r.second_codec in order:
            mat[r.source_codec][r.second_codec] = 100 * float(r.eer)
    best: dict[str, set] = {}
    worst: dict[str, set] = {}
    for d in order:
        vv = [
            (s, round(mat[s][d], 2)) for s in order if d in mat[s] and s != CONFOUNDED
        ]
        if len({v for _, v in vv}) >= 2:
            lo = min(v for _, v in vv)
            hi = max(v for _, v in vv)
            best[d] = {s for s, v in vv if v == lo}
            worst[d] = {s for s, v in vv if v == hi}
    emph = emphasis_for(stem)
    lines = [
        header,
        "\\begin{tabular}{l" + "c" * ncol + "}",
        "\\toprule",
        f" & \\multicolumn{{{ncol}}}{{c}}{{Second codec}} \\\\",
        f"\\cmidrule(lr){{2-{ncol + 1}}}",
        "Source & " + " & ".join(lab for _, lab in CODECS) + " \\\\",
        "\\midrule",
    ]
    for s, slab in CODECS:
        cells = []
        for d, _ in CODECS:
            if d not in mat[s]:
                cells.append("--")
                continue
            v = f"{mat[s][d]:.2f}"
            if s != CONFOUNDED and d != CONFOUNDED:
                if s in best.get(d, ()):
                    v = shade_best(v, emphasis=emph)
                elif s in worst.get(d, ()):
                    v = shade_worst(v, emphasis=emph)
            cells.append(v)
        lines.append(slab + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument(
        "--input-dir", default=None, help="default: OUTPUT_ROOT/recompression"
    )
    src.add_argument(
        "--from-results",
        action="store_true",
        help="read the shipped paper results (results/recompression)",
    )
    ap.add_argument("--out-dir", default=None, help="default: OUTPUT_ROOT/tables")
    ap.add_argument(
        "--paper-header",
        action="store_true",
        help="use the comment line of the published tables (byte-identical output)",
    )
    args = ap.parse_args(argv)
    setup_logging()

    if args.from_results:
        in_dir = config.results_dir("recompression")
    elif args.input_dir:
        in_dir = Path(args.input_dir)
    else:
        in_dir = config.output_dir("recompression")
    out_dir = Path(args.out_dir) if args.out_dir else config.output_dir("tables")
    header = PAPER_HEADER if args.paper_header else HEADER
    written = 0
    for ds, budget in CELLS:
        csv = in_dir / f"recompression_{ds}_{budget}.csv"
        stem = table_stem(ds, budget)
        if not csv.exists():
            log.warning("skip %s: %s is missing", stem, csv)
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / f"{stem}.tex").write_text(render(pd.read_csv(csv), stem, header))
        log.info("wrote %s", out_dir / f"{stem}.tex")
        written += 1
    return 0 if written else 1


if __name__ == "__main__":
    raise SystemExit(main())
