def test_codec_properties_fit_subset_rule(tmp_path):
    rows = []
    for res in (112, 224):
        rows += [
            ("colorferet", res, 1024, "jpeg", 11335, 99.95),
            ("colorferet", res, 1024, "neural_bmshj2018", 300, 59.3),
            ("colorferet", res, 512, "jpeg", 11335, 1.0),
        ]
    df = pd.DataFrame(
        rows, columns=["dataset", "res", "budget", "codec", "n", "pct_holding"]
    )
    p = tmp_path / "s.csv"
    df.to_csv(p, index=False)
    fits = props.fit_values(p)
    assert props.fit_cell("jpeg", fits) == "100\\,/\\,100"
    assert props.fit_cell("neural_bmshj2018", fits) == "n/a"


def test_jpegai_speed_table_directions():
    base = {"encode_ms_median": 1.0, "bytes_median": 1108, "lpips": 0.15}
    rows = []
    for op, dec_cpu, dec_gpu, enc, psnr in (
        ("SOP", 571.7, 654.9, 1956.0, 34.99),
        ("BOP", 599.4, 631.9, 1819.4, 35.36),
        ("HOP", 1191.9, 656.5, 1945.1, 35.93),
    ):
        common = {**base, "op_point": op, "psnr": psnr, "ssim": 0.9, "id_cos": 0.94}
        rows.append({**common, "device": "cpu", "decode_ms_median": dec_cpu})
        rows.append(
            {
                **common,
                "device": "gpu",
                "decode_ms_median": dec_gpu,
                "encode_ms_median": enc,
            }
        )
    lines = jai_speed.render(pd.DataFrame(rows)).splitlines()
    sop, bop, hop = (ln for ln in lines if ln[:3] in ("SOP", "BOP", "HOP"))
    assert sop.startswith(
        "SOP & 1 & \\cellcolor{green!25}572 & 655 & \\cellcolor{red!22}1956"
    )
    assert "\\cellcolor{green!25}632" in bop and "\\cellcolor{red!22}656" in hop
    assert "\\cellcolor{green!25}35.93" in hop and "\\cellcolor{red!22}34.99" in sop
    assert "cellcolor" not in sop.split(" & ")[-1]  # bytes are not ranked
    assert "0.940" in sop and "cellcolor" not in sop.split(" & ")[7]  # all tie


def test_jpegai_kk_eer_and_sampling(tmp_path):
    emb = np.array([[1, 0], [0.99, 0.1], [0, 1], [0.1, 0.99]], dtype=np.float32)
    assert jai_kk.all_pairs_eer(emb, ["a", "a", "b", "b"]) == 0.0
    assert (
        jai_kk.psnr(np.zeros((2, 2, 3), np.uint8), np.zeros((2, 2, 3), np.uint8))
        == 99.0
    )
    for ident, n in (("p1", 3), ("p2", 1), ("p3", 2)):
        (tmp_path / ident).mkdir()
        for k in range(n):
            (tmp_path / ident / f"{ident}_{k}.png").write_bytes(b"")
    s1 = jai_kk.sample_crops(tmp_path, 4, 8, 0)
    assert s1 == jai_kk.sample_crops(tmp_path, 4, 8, 0)
    assert {s[0] for s in s1} == {"p1", "p3"}  # identities with >= 2 crops only
    assert len(s1) == 4 and len(jai_kk.sample_crops(tmp_path, 10, 1, 0)) == 2


def test_jpegai_kk_table_shading():
    rows = [("arcface_antelopev2", "aligned", 0.077, 1.0, 99.0, 0)]
    rows += [
        ("arcface_antelopev2", op, e, c, p, b)
        for op, e, c, p, b in (
            ("SOP", 0.140, 0.9347, 31.08, 1111),
            ("BOP", 0.147, 0.9350, 31.34, 1111),
            ("HOP", 0.140, 0.9407, 31.95, 1113),
        )
    ]
    df = pd.DataFrame(
        rows, columns=["model", "op_point", "eer", "id_cos", "psnr", "bytes"]
    )
    tex = jai_kk.render_table(df)
    assert "SOP & 1 & \\cellcolor{green!25}0.140 & -- &" in tex  # first of a tie
    assert "HOP & 3 & 0.140 &" in tex
    assert (
        "\\cellcolor{"
        not in jai_kk.render_table(df, shade_eer=False)
        .split("SOP & 1 & ")[1]
        .split(" & ")[0]
    )


