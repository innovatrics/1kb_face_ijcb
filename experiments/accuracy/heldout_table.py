r"""Held-out matcher table: CVLface IR-101 EER and FNMR@1e-4 (Section 7.6).

Reads ``accuracy/metrics.csv`` and writes ``heldout_cvlface.tex``
(``tab:heldout-cvlface``): EER (percent) with FNMR at FMR = 1e-4 (percent, in
parentheses) of ``cvlface_ir101`` at 112 px for Color FERET and AI-Solutions-KK at
1024 and 512 B. CVLface IR-101 is used neither in codec training nor as an anchor.
Rows are the ten codecs scored at full support on both datasets (the CompressAI
baselines are left out), plus the aligned reference spanning both budget columns.
Lowest / highest EER per column are shaded (bold / underlined).

Examples
--------
    python experiments/accuracy/heldout_table.py --from-results --paper-header
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config
from face1kb.report.latex import BEST_FILL, WORST_FILL, finalize_table

log = logging.getLogger("heldout_table")

HEADER = "% generated by experiments/accuracy/heldout_table.py"
PAPER_HEADER = "% generated by generate_heldout_table.py"
MODEL = "cvlface_ir101"
RES = 112
CODECS = [
    ("jpeg_ai", "JPEG-AI"),
    ("webp", "WebP"),
    ("avif", "AVIF"),
    ("heif", "HEIF"),
    ("jpeg_xl", "JPEG~XL"),
    ("ours_accurate", "Ours-ACCURATE"),
    ("ours_fast", "Ours-FAST"),
    ("jpeg_fzt", "JPEG-FzT"),
    ("jpeg", "JPEG"),
    ("jpeg2000", "JPEG~2000"),
]
COLS = [("colorferet", 1024), ("colorferet", 512), ("kk", 1024), ("kk", 512)]


def table(df: pd.DataFrame, header: str) -> str:
    """Colour-shaded LaTeX tabular."""
    df = df[(df.model == MODEL) & (df.res == RES) & (df.suffix.isna())]

    def pick(ds, budget, codec, col):
        if codec is None:
            r = df[(df.dataset == ds) & (df.kind == "aligned")]
        else:
            r = df[(df.dataset == ds) & (df.budget == budget) & (df.codec == codec)]
        if len(r) and r[col].notna().any():
            return float(r[col].iloc[0]) * 100
        return None

    grid = {c: [pick(ds, b, c, "eer") for ds, b in COLS] for c, _ in CODECS}
    tail = {c: [pick(ds, b, c, "fnmr_0.0001") for ds, b in COLS] for c, _ in CODECS}
    best = [
        min((v[i] for v in grid.values() if v[i] is not None), default=None)
        for i in range(len(COLS))
    ]
    worst = [
        max((v[i] for v in grid.values() if v[i] is not None), default=None)
        for i in range(len(COLS))
    ]

    def cell(v, t, i):
        if v is None:
            return "n/a"
        s = f"{v:.2f}"
        if t is not None:
            s += f"\\,{{\\scriptsize({t:.1f})}}"
        if best[i] is not None and v == best[i]:
            s = f"\\cellcolor{{{BEST_FILL}}}{s}"
        elif worst[i] is not None and v == worst[i]:
            s = f"\\cellcolor{{{WORST_FILL}}}{s}"
        return s

    ref = " & ".join(
        f"\\multicolumn{{2}}{{c}}{{{pick(ds, 0, None, 'eer'):.2f}"
        f"\\,{{\\scriptsize({pick(ds, 0, None, 'fnmr_0.0001'):.1f})}}}}"
        for ds in ("colorferet", "kk")
    )
    lines = [
        header,
        "\\begin{tabular}{lcccc}",
        "  \\toprule",
        "  & \\multicolumn{2}{c}{Color~FERET}"
        " & \\multicolumn{2}{c}{AI-Solutions-KK} \\\\",
        "  \\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        "  Codec & $1024$\\,B & $512$\\,B & $1024$\\,B & $512$\\,B \\\\",
        "  \\midrule",
        f"  \\emph{{aligned}} (ref.) & {ref} \\\\",
        "  \\midrule",
    ]
    for c, name in CODECS:
        cells = " & ".join(cell(grid[c][i], tail[c][i], i) for i in range(len(COLS)))
        lines.append(f"  {name:14s}& {cells} \\\\")
    lines += ["  \\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the held-out matcher table."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--input-root", default=None, help="default: outputs/")
    src.add_argument(
        "--from-results", action="store_true", help="read the shipped results/"
    )
    ap.add_argument("--metrics", default=None, help="default: accuracy/metrics.csv")
    ap.add_argument("--out-dir", default=None, help="default: outputs/tables")
    ap.add_argument(
        "--paper-header", action="store_true", help="comment line of the paper"
    )
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    root = (
        config.RESULTS_ROOT
        if args.from_results
        else Path(args.input_root or config.OUTPUT_ROOT)
    )
    df = pd.read_csv(Path(args.metrics or root / "accuracy" / "metrics.csv"))
    out_dir = Path(args.out_dir) if args.out_dir else config.output_dir("tables")
    out_dir.mkdir(parents=True, exist_ok=True)
    header = PAPER_HEADER if args.paper_header else HEADER
    out = out_dir / "heldout_cvlface.tex"
    out.write_text(finalize_table("heldout_cvlface", table(df, header)))
    log.info("wrote %s", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
