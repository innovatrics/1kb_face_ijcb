r"""LaTeX tables of the adversarial study, generated from ``sanitization.csv``.

Every number is a mean over the matchers of the input (the paper: the four anchors
``arcface_antelopev2``, ``lvface_l``, ``topofr_r100``, ``edgeface_xs``) of one column
of ``sanitization.csv`` (written by ``analyze.py``).

Residual tables (``sanitization_<attack>[_kk].tex``): one row per codec, one column
per (``eps``, budget); the cell is the mean ``residual`` (lower = stronger
sanitization). Rows are ordered by their mean over the columns. A codec is marked
``$^\ddagger$`` and excluded from the best/worst shading when it has data for fewer
matchers than requested or for fewer crops than the best-covered codec (the paper:
JPEG-FzT, JPEG-AI and the two CompressAI codecs, attacked with HFC on 300 Color FERET
crops). A column cell that was never measured reads ``---``. The best (lowest) cell
of each column is shaded green and bold, the worst red and underlined
(:mod:`face1kb.report.latex`).

=========================  ================  ===================================
file                       dataset / attack  paper table
=========================  ================  ===================================
``sanitization_hfc``       Color FERET, HFC  ``tab:sanitization-hfc``
``sanitization_clip``      Color FERET, CLIP ``tab:sanitization-clip``
``sanitization_liae``      Color FERET, Li-AE ``tab:sanitization-liae``
``sanitization_hfc_kk``    KK, HFC           ``tab:sanitization-hfc-kk``
``attack_strength``        Color FERET       ``tab:attack-strength``
``ours_defense``           Color FERET       ``tab:ours-defense``
=========================  ================  ===================================

``attack_strength``: mean ``cos_adv`` (identity cosine of the uncompressed
adversarial crop to its clean reference; lower = stronger attack) per attack and
``eps``, taken from the cells of full crop coverage; the strongest attack per column
is bold. ``ours_defense``: the residual of Ours-FAST and Ours-ACCURATE next to the
strongest (JPEG 2000) and weakest classical (WebP) sanitizer, under the three attacks
at ``eps = 0.06``; the lowest residual per column is bold. The paper prints these two
tables inline, in the same content.

Input: ``OUTPUT_ROOT/adversarial/sanitization.csv``, or the shipped paper results
with ``--from-results``, or any file with ``--input``. Output:
``OUTPUT_ROOT/adversarial/<table>.tex`` (``--out-dir`` to change). CPU, seconds.

Examples
--------
    python experiments/adversarial/generate_sanitization_table.py --from-results
    python experiments/adversarial/generate_sanitization_table.py \
        --tables sanitization_hfc_kk --out-dir tables
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config
from face1kb.data.cli_utils import parse_list, setup_logging
from face1kb.eval.embeddings import ANCHOR_MODELS
from face1kb.report.latex import emphasis_for, shade_best, shade_worst

log = logging.getLogger("adversarial.tables")

HEADER = "% generated by generate_sanitization_table.py"
EPS = (0.03, 0.06, 0.10)
BUDGETS = (512, 1024)
#: Row labels of the codecs.
LABELS = {
    "jpeg2000": "JPEG~2000",
    "jpeg": "JPEG",
    "heif": "HEIF",
    "avif": "AVIF",
    "jpeg_fzt": "JPEG-FzT",
    "jpeg_xl": "JPEG~XL",
    "webp": "WebP",
    "ours_fast": "Ours-FAST",
    "ours_accurate": "Ours-ACCURATE",
    "jpeg_ai": "JPEG-AI",
    "neural_bmshj2018": "bmshj2018",
    "neural_mbt2018_mean": "mbt2018",
}
#: Residual tables: file stem -> (dataset, attack).
RESIDUAL_TABLES: dict[str, tuple[str, str]] = {
    "sanitization_hfc": ("colorferet", "hfc"),
    "sanitization_clip": ("colorferet", "clip"),
    "sanitization_liae": ("colorferet", "liae"),
    "sanitization_hfc_kk": ("kk", "hfc"),
}
#: Rows of ``attack_strength``: attack -> label.
ATTACK_LABELS = {
    "liae": "Li-AE (trained proxy AE + ILA)",
    "hfc": "HFC (training-free, frequency)",
    "clip": "CLIP-surrogate (foundation)",
}
#: Column groups of ``ours_defense``: attack -> label.
DEFENSE_ATTACKS = {"hfc": "HFC", "clip": "CLIP", "liae": "Li-AE"}
#: Rows of ``ours_defense``.
DEFENSE_CODECS = ("jpeg2000", "webp", "ours_fast", "ours_accurate")
DEFENSE_EPS = 0.06
TABLES = (*RESIDUAL_TABLES, "attack_strength", "ours_defense")


def _num(v: float) -> str:
    return f"{v:.3f}" if v >= 0 else f"$-{abs(v):.3f}$"


def residual_table(
    df: pd.DataFrame, dataset: str, attack: str, stem: str, models=ANCHOR_MODELS
) -> str | None:
    """Residual table of one (dataset, attack); ``None`` if it has no rows."""
    sub = df[(df.dataset == dataset) & (df.attack == attack) & df.model.isin(models)]
    if sub.empty:
        return None
    piv = sub.pivot_table(
        index="codec", columns=["eps", "budget"], values="residual", aggfunc="mean"
    )
    # coverage counts only matchers and crops that produced a value
    got = sub.dropna(subset=["residual"])
    cov = got.groupby("codec").model.nunique().reindex(sub.codec.unique()).fillna(0)
    sup = got.groupby("codec").n.max()
    cols = [(e, b) for e in EPS for b in BUDGETS if (e, b) in piv.columns]
    order = piv[cols].mean(axis=1).sort_values().index.tolist()
    full = int(sup.max())
    reduced = {c for c in order if int(cov[c]) != len(models) or int(sup[c]) < full}
    ranked = [c for c in order if c not in reduced] or order
    best = {c: piv.loc[ranked, c].min() for c in cols}
    worst = {c: piv.loc[ranked, c].max() for c in cols}
    emph = emphasis_for(stem)

    lines = [
        HEADER,
        "\\begin{tabular}{l" + "c" * len(cols) + "}",
        "\\toprule",
        "& "
        + " & ".join(
            f"\\multicolumn{{{len(BUDGETS)}}}{{c}}{{$\\varepsilon={e:g}$}}" for e in EPS
        )
        + " \\\\",
        " ".join(f"\\cmidrule(lr){{{2 + i * 2}-{3 + i * 2}}}" for i in range(len(EPS))),
        "Codec & " + " & ".join(f"{b}\\,B" for _e, b in cols) + " \\\\",
        "\\midrule",
    ]
    for codec in order:
        cells = []
        for c in cols:
            v = piv.loc[codec, c]
            if pd.isna(v):
                cells.append("---")
                continue
            s = _num(v)
            if codec not in reduced:
                if v == best[c]:
                    s = shade_best(s, emph)
                elif v == worst[c]:
                    s = shade_worst(s, emph)
            cells.append(s)
        name = LABELS.get(codec, codec)
        if codec in reduced:
            name += "$^\\ddagger$"
        lines.append(f"{name} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    log.info(
        "%s: %d codecs; reduced coverage (unshaded, daggered): %s",
        stem,
        len(order),
        sorted(reduced),
    )
    return "\n".join(lines) + "\n"


def _full_coverage(sub: pd.DataFrame) -> pd.DataFrame:
    """Rows of the cells with the largest crop count ``n`` of each group."""
    return sub[sub.n == sub.n.max()]


def attack_strength(
    df: pd.DataFrame, dataset: str = "colorferet", models=ANCHOR_MODELS
) -> str:
    """Mean ``cos_adv`` per attack and ``eps`` (the uncompressed attack strength).

    ``cos_adv`` is measured on the crops of each cell; within a (matcher, attack,
    ``eps``) it is the same for every cell of full crop coverage, which is the
    value used.
    """
    sub = df[(df.dataset == dataset) & df.model.isin(models)].dropna(subset=["cos_adv"])
    vals: dict[tuple[str, float], float] = {}
    for (attack, eps), g in sub.groupby(["attack", "eps"]):
        per_model = [
            _full_coverage(x).cos_adv.iloc[0]
            for _m, x in g.groupby("model", sort=False)
        ]
        vals[(attack, eps)] = sum(per_model) / len(per_model)
    lines = [
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "Attack & " + " & ".join(f"$\\varepsilon={e:.2f}$" for e in EPS) + " \\\\",
        "\\midrule",
    ]
    attacks = [a for a in ATTACK_LABELS if any(k[0] == a for k in vals)]
    best = {
        e: min(vals[(a, e)] for a in attacks if (a, e) in vals)
        for e in EPS
        if any((a, e) in vals for a in attacks)
    }
    for a in attacks:
        cells = []
        for e in EPS:
            v = vals.get((a, e))
            if v is None:
                cells.append("---")
                continue
            s = _num(v)
            cells.append(f"\\textbf{{{s}}}" if v == best[e] else s)
        lines.append(f"{ATTACK_LABELS[a]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def ours_defense(
    df: pd.DataFrame, dataset: str = "colorferet", models=ANCHOR_MODELS
) -> str:
    """Residuals of the two face1kb codecs next to JPEG 2000 and WebP (eps 0.06)."""
    sub = df[
        (df.dataset == dataset)
        & df.model.isin(models)
        & (df.eps == DEFENSE_EPS)
        & df.codec.isin(DEFENSE_CODECS)
    ]
    piv = sub.pivot_table(
        index="codec", columns=["attack", "budget"], values="residual", aggfunc="mean"
    )
    cols = [(a, b) for a in DEFENSE_ATTACKS for b in BUDGETS]
    span = len(BUDGETS)
    groups = " & ".join(
        f"\\multicolumn{{{span}}}{{c}}{{{lbl}, $\\varepsilon={DEFENSE_EPS:.2f}$}}"
        for lbl in DEFENSE_ATTACKS.values()
    )
    rules = "".join(
        f"\\cmidrule(lr){{{2 + i * 2}-{3 + i * 2}}}"
        for i in range(len(DEFENSE_ATTACKS))
    )
    lines = [
        "\\begin{tabular}{l" + "c" * len(cols) + "}",
        "\\toprule",
        f"& {groups} \\\\",
        rules,
        "Codec & " + " & ".join(f"{b}\\,B" for _a, b in cols) + " \\\\",
        "\\midrule",
    ]
    rows = [c for c in DEFENSE_CODECS if c in piv.index]
    best = {c: piv.loc[rows, c].min() for c in cols if c in piv.columns}
    for codec in rows:
        cells = []
        for c in cols:
            v = piv.loc[codec, c] if c in piv.columns else float("nan")
            if pd.isna(v):
                cells.append("---")
                continue
            s = _num(v)
            cells.append(f"\\textbf{{{s}}}" if v == best[c] else s)
        lines.append(f"{LABELS[codec]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def build(df: pd.DataFrame, stem: str, models=ANCHOR_MODELS) -> str | None:
    """Text of table ``stem`` (see :data:`TABLES`)."""
    if stem in RESIDUAL_TABLES:
        dataset, attack = RESIDUAL_TABLES[stem]
        return residual_table(df, dataset, attack, stem, models)
    if stem == "attack_strength":
        return attack_strength(df, models=models)
    if stem == "ours_defense":
        return ours_defense(df, models=models)
    raise ValueError(f"unknown table {stem!r}; choose from {TABLES}")


def main(argv: list[str] | None = None) -> int:
    """Write the adversarial-study tables."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--input", default=None, help="sanitization.csv to read")
    src.add_argument(
        "--from-results", action="store_true", help="read the shipped paper results"
    )
    ap.add_argument("--tables", default=",".join(TABLES))
    ap.add_argument("--models", default=",".join(ANCHOR_MODELS))
    ap.add_argument("--out-dir", default=None)
    args = ap.parse_args(argv)
    setup_logging()

    if args.input:
        path = Path(args.input)
    elif args.from_results:
        path = config.results_dir("adversarial", "sanitization.csv")
    else:
        path = config.output_dir("adversarial", "sanitization.csv")
    if not path.is_file():
        raise SystemExit(f"{path} not found (run analyze.py or pass --from-results)")
    df = pd.read_csv(path)
    out_dir = Path(args.out_dir) if args.out_dir else config.output_dir("adversarial")
    out_dir.mkdir(parents=True, exist_ok=True)
    models = tuple(parse_list(args.models))
    status = 0
    for stem in parse_list(args.tables):
        text = build(df, stem, models)
        if text is None:
            log.error("%s: no rows in %s", stem, path)
            status = 1
            continue
        (out_dir / f"{stem}.tex").write_text(text)
        log.info("wrote %s", out_dir / f"{stem}.tex")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
