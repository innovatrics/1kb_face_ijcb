r"""Rate-EER tables of the core grid (Section 5.2, ``tab:rate-eer-*``).

Reads ``accuracy/metrics.csv`` and writes, per dataset and matcher,
``rate_eer_<dataset>_<model>.tex``: EER in percent with its 95 % bootstrap interval,
one row per codec and one column per resolution x budget (64-224 px, 1024 / 512 B),
plus the aligned reference row. Only the core grid is used (empty source suffix).
The lowest EER of a column is shaded green and bold, the highest red and underlined
(:mod:`face1kb.report.latex`). A cell whose codec kept fewer than 99.5 % of its
files within the budget (``pct_holding`` of ``codec_comparison/file_size_summary
.csv``) carries ``$^\dagger$``; without that file no daggers are written.

The paper prints the tables of the four anchors (``--models anchor``, the default);
``--models all`` writes one per matcher of ``metrics.csv``.

Examples
--------
    python experiments/accuracy/rate_eer.py --from-results --paper-header
    python experiments/accuracy/rate_eer.py --models all --out-dir /tmp/tables
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config
from face1kb.eval.embeddings import ANCHOR_MODELS
from face1kb.report.latex import BEST_FILL, WORST_FILL, finalize_table

log = logging.getLogger("rate_eer")

HEADER = "% rate–EER for the core grid — generated by experiments/accuracy/rate_eer.py"
PAPER_HEADER = "% rate–EER for the core grid — generated by generate_rate_eer.py"
#: Row order and labels of the table.
CODEC_LABEL = {
    "jpeg": "JPEG",
    "jpeg2000": "JPEG 2000",
    "webp": "WebP",
    "jpeg_xl": "JPEG XL",
    "avif": "AVIF",
    "heif": "HEIF",
    "jpeg_fzt": "JPEG-FzT",
    "jpeg_ai": "JPEG-AI",
    "neural_bmshj2018": "bmshj2018",
    "neural_mbt2018_mean": "mbt2018",
    "ours_fast": "Ours-FAST",
    "ours_accurate": "Ours-ACC",
}
BUDGETS = (1024, 512)
#: A cell is marked over budget when fewer than this percentage of files fit.
HOLDING_MIN = 99.5


def over_budget(path: Path) -> set:
    """``(dataset, codec, res, budget)`` cells with ``pct_holding < 99.5``."""
    if not path.is_file():
        log.warning("%s not found: no over-budget daggers", path)
        return set()
    d = pd.read_csv(path)
    return {
        (r.dataset, r.codec, int(r.res), int(r.budget))
        for r in d.itertuples()
        if float(r.pct_holding) < HOLDING_MIN
    }


def _fmt_eer(row) -> str:
    """``eer (lo–hi)`` in percent when the CI is present, else ``eer``."""
    e = f"{100 * row.eer:.2f}"
    if pd.notna(row.get("eer_lo")):
        return f"{e} ({100 * row.eer_lo:.2f}–{100 * row.eer_hi:.2f})"
    return e


def table(df: pd.DataFrame, dataset: str, model: str, over: set, header: str) -> str:
    """Colour-shaded LaTeX tabular of one dataset and matcher ('' if no rows)."""
    g = df[
        (df.dataset == dataset)
        & (df.model == model)
        & (df.suffix.fillna("") == "")
        & df.eer.notna()
    ]
    if g.empty:
        return ""
    resolutions = sorted(g.res.unique())
    comp = g[g.kind == "compressed"]
    aligned = g[g.kind == "aligned"].set_index("res")
    cols = [(r, b) for r in resolutions for b in BUDGETS]
    lines = [
        header,
        "\\begin{tabular}{l" + "r" * len(cols) + "}",
        "\\toprule",
        "Codec & " + " & ".join(f"{r}px/{b}B" for r, b in cols) + " \\\\",
        "\\midrule",
    ]
    ref = []
    for r in resolutions:
        ref += [_fmt_eer(aligned.loc[r]) if r in aligned.index else "--"]
        ref += [""] * (len(BUDGETS) - 1)
    lines += ["aligned (ref) & " + " & ".join(ref) + " \\\\", "\\midrule"]
    val: dict = {}
    for codec in CODEC_LABEL:
        sub = comp[comp.codec == codec]
        val[codec] = {}
        for r, b in cols:
            hit = sub[(sub.res == r) & (sub.budget == b)]
            if len(hit):
                val[codec][(r, b)] = (float(hit.iloc[0].eer), _fmt_eer(hit.iloc[0]))
    best, worst = {}, {}
    for col in cols:
        vv = [(c, val[c][col][0]) for c in CODEC_LABEL if col in val[c]]
        if len(vv) >= 2:
            best[col] = min(vv, key=lambda x: x[1])[0]
            worst[col] = max(vv, key=lambda x: x[1])[0]
    for codec, label in CODEC_LABEL.items():
        if not val[codec]:
            continue
        cells = []
        for col in cols:
            if col not in val[codec]:
                cells.append("--")
                continue
            s = val[codec][col][1]
            if codec == best.get(col):
                s = f"\\cellcolor{{{BEST_FILL}}}{s}"
            elif codec == worst.get(col):
                s = f"\\cellcolor{{{WORST_FILL}}}{s}"
            if (dataset, codec, col[0], col[1]) in over:
                s += "$^\\dagger$"
            cells.append(s)
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the rate-EER tables."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--input-root", default=None, help="default: outputs/")
    src.add_argument(
        "--from-results", action="store_true", help="read the shipped results/"
    )
    ap.add_argument("--metrics", default=None, help="default: accuracy/metrics.csv")
    ap.add_argument(
        "--file-sizes",
        default=None,
        help="default: codec_comparison/file_size_summary.csv of the input root",
    )
    ap.add_argument(
        "--models", default="anchor", help="'anchor', 'all' or a comma list"
    )
    ap.add_argument("--out-dir", default=None, help="default: outputs/tables")
    ap.add_argument(
        "--paper-header", action="store_true", help="comment line of the paper"
    )
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    root = (
        config.RESULTS_ROOT
        if args.from_results
        else Path(args.input_root or config.OUTPUT_ROOT)
    )
    df = pd.read_csv(Path(args.metrics or root / "accuracy" / "metrics.csv"))
    sizes = Path(args.file_sizes or root / "codec_comparison" / "file_size_summary.csv")
    over = over_budget(sizes)
    if args.models == "anchor":
        models = list(ANCHOR_MODELS)
    elif args.models == "all":
        models = sorted(df.model.unique())
    else:
        models = [m.strip() for m in args.models.split(",") if m.strip()]
    out_dir = Path(args.out_dir) if args.out_dir else config.output_dir("tables")
    out_dir.mkdir(parents=True, exist_ok=True)
    header = PAPER_HEADER if args.paper_header else HEADER
    for dataset in sorted(df.dataset.unique()):
        for model in models:
            tex = table(df, dataset, model, over, header)
            if not tex:
                continue
            stem = f"rate_eer_{dataset}_{model}"
            (out_dir / f"{stem}.tex").write_text(finalize_table(stem, tex))
            log.info("wrote %s", out_dir / f"{stem}.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
