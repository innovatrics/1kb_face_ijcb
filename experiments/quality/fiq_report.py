r"""Face-image-quality grid table and figure from the FIQ aggregates (CPU).

Reads ``<input-root>/quality/fiq_{colorferet,kk}.csv`` (``fiq.py``;
``--from-results`` reads the shipped paper results) and writes

* ``fiq_grid.tex`` (tab:fiq) into ``--out-dir`` (default
  ``$FACE1KB_OUTPUT_ROOT/tables``): the mean FIQ per codec for
  {112, 224} px x {1024, 512} B on both datasets, the original first;
* ``fiq_by_codec.png`` (fig:fiq) into ``--fig-dir`` (default
  ``$FACE1KB_OUTPUT_ROOT/figures``): per-codec bars in a 2 x 2 grid of cells, the
  original crops as dashed lines.

Shading (higher FIQ is better; the original row does not compete):

* ``--shading printed`` (default): ranks the values rounded to the printed three
  decimals; every cell tied at the extreme is shaded and a column whose printed
  values all tie stays unshaded;
* ``--shading raw``: ranks the unrounded means and shades exactly one best and one
  worst cell per column; this is the rule of the published table (arXiv v1).

Examples
--------
    python experiments/quality/fiq_report.py --from-results --shading raw
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import numpy as np

from face1kb import config
from face1kb.data.cli_utils import setup_logging
from face1kb.report import latex, style

log = logging.getLogger("quality.fiq_report")

#: (res, budget) cells of the grid, in column order.
GRID = ((112, 1024), (112, 512), (224, 1024), (224, 512))
#: Codec rows after the original.
CODEC_ORDER = (
    "jpeg",
    "jpeg2000",
    "webp",
    "jpeg_xl",
    "avif",
    "heif",
    "jpeg_fzt",
    "jpeg_ai",
    "ours_fast",
    "ours_accurate",
)
LABELS = {
    "original": "Original",
    "jpeg": "JPEG",
    "jpeg2000": "JPEG 2000",
    "webp": "WebP",
    "jpeg_xl": "JPEG XL",
    "avif": "AVIF",
    "heif": "HEIF",
    "jpeg_fzt": "JPEG-FzT",
    "jpeg_ai": "JPEG-AI",
    "ours_fast": "Ours-FAST",
    "ours_accurate": "Ours-ACC",
}
DP = 3
#: First comment line of the generated table and of the published copy.
HEADER = (
    "% generated by experiments/quality/fiq_report.py -- SER-FIQ-style FIQ grid "
    "(arcface_antelopev2)"
)
PAPER_HEADER = (
    "% generated by generate_fiq.py -- SER-FIQ-style FIQ grid (arcface_antelopev2)"
)


def _look(df, ds: str, res: int, budget: int, codec: str):
    r = df[
        (df.dataset == ds)
        & (df.res == res)
        & (df.budget == budget)
        & (df.codec == codec)
    ]
    return float(r.fiq_mean.iloc[0]) if len(r) else None


def shade_column(values: dict, rule: str = "printed") -> dict:
    """``{codec: "best" | "worst"}`` of one column (higher is better, no original)."""
    items = {
        k: v
        for k, v in values.items()
        if k != "original" and v is not None and not np.isnan(v)
    }
    if rule == "raw":
        if len(items) < 2:
            return {}
        return {
            min(items, key=items.get): "worst",
            max(items, key=items.get): "best",
        }
    if rule != "printed":
        raise ValueError(f"unknown shading rule {rule!r}")
    items = {k: round(v, DP) for k, v in items.items()}
    if len(set(items.values())) < 2:
        return {}
    hi, lo = max(items.values()), min(items.values())
    out = {k: "worst" for k, v in items.items() if v == lo}
    out.update({k: "best" for k, v in items.items() if v == hi})
    return out


def _cell(val, shade) -> str:
    s = "--" if val is None or np.isnan(val) else f"{val:.{DP}f}"
    if shade == "best":
        return latex.shade_best(s, emphasis=False)
    if shade == "worst":
        return latex.shade_worst(s, emphasis=False)
    return s


def grid_table(df, rule: str = "printed", header: str = HEADER) -> str:
    """Render the FIQ grid table (codec rows x dataset/res/budget columns)."""
    rows = ("original", *CODEC_ORDER)
    cols = [(ds, res, b) for ds in ("colorferet", "kk") for (res, b) in GRID]
    shade = {
        col: shade_column({c: _look(df, *col, c) for c in rows}, rule) for col in cols
    }
    lines = [
        header,
        "\\begin{tabular}{l" + "c" * len(cols) + "}",
        "\\toprule",
        " & \\multicolumn{4}{c}{Color FERET} "
        "& \\multicolumn{4}{c}{AI-Solutions-KK} \\\\",
        "\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}",
        "Codec & " + " & ".join(f"{res}/{b}" for (_, res, b) in cols) + " \\\\",
        "\\midrule",
    ]
    for c in rows:
        cells = [_cell(_look(df, *col, c), shade[col].get(c)) for col in cols]
        lines.append(LABELS[c] + " & " + " & ".join(cells) + " \\\\")
        if c == "original":
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return latex.finalize_table("fiq_grid", "\n".join(lines))


def figure(df, out: Path) -> Path:
    """FIQ-per-codec bars as 2 x 2 small multiples over the grid cells."""
    style.use_agg()
    import matplotlib.pyplot as plt  # noqa: PLC0415

    colors = style.DATASET_COLORS
    fig, axes = plt.subplots(2, 2, figsize=(13, 9))
    for ax, (res, b) in zip(axes.ravel(), GRID):
        vals = {}
        for ds in ("colorferet", "kk"):
            v = [_look(df, ds, res, b, c) for c in CODEC_ORDER]
            vals[ds] = [np.nan if x is None else x for x in v]
            o = _look(df, ds, res, b, "original")
            vals[ds + "_orig"] = np.nan if o is None else o
        x = np.arange(len(CODEC_ORDER))
        ax.bar(
            x - 0.2,
            vals["colorferet"],
            0.4,
            label="Color FERET",
            color=colors["colorferet"],
        )
        ax.bar(x + 0.2, vals["kk"], 0.4, label="AI-Solutions-KK", color=colors["kk"])
        for ds in ("colorferet", "kk"):
            if not np.isnan(vals[ds + "_orig"]):
                ax.axhline(
                    vals[ds + "_orig"], ls="--", lw=1.1, color=colors[ds], alpha=0.9
                )
        allv = [
            v
            for v in vals["colorferet"]
            + vals["kk"]
            + [vals["colorferet_orig"], vals["kk_orig"]]
            if not np.isnan(v)
        ]
        ax.set_ylim(max(0.0, min(allv) - 0.03), min(1.0, max(allv) + 0.02))
        ax.set_xticks(x)
        ax.set_xticklabels(
            [LABELS[c] for c in CODEC_ORDER], rotation=30, ha="right", fontsize=8
        )
        ax.set_title(f"{res} px / {b} B", fontsize=11)
        ax.set_ylabel("FIQ (SER-FIQ-style)")
        ax.grid(axis="y", ls=":", alpha=0.5)
    axes[0, 0].legend(fontsize=9, framealpha=0.9)
    fig.suptitle(
        "Face Image Quality per codec across the resolution x budget grid "
        "(higher = better; dashed = uncompressed original)",
        fontsize=12,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.97))
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=style.FIGURE_DPI["fiq"], facecolor="white")
    plt.close(fig)
    return out


def main(argv: list[str] | None = None) -> int:
    """Write fiq_grid.tex and fiq_by_codec.png."""
    import pandas as pd  # noqa: PLC0415

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument(
        "--input-root",
        type=Path,
        default=None,
        help="folder holding quality/ (default: $FACE1KB_OUTPUT_ROOT)",
    )
    src.add_argument("--from-results", action="store_true", help="read <repo>/results")
    ap.add_argument("--shading", choices=("printed", "raw"), default="printed")
    ap.add_argument(
        "--paper-header",
        action="store_true",
        help="write the first comment line of the published table",
    )
    ap.add_argument("--out-dir", type=Path, default=None)
    ap.add_argument("--fig-dir", type=Path, default=None)
    ap.add_argument("--no-figure", action="store_true")
    args = ap.parse_args(argv)
    setup_logging()

    base = config.RESULTS_ROOT if args.from_results else args.input_root
    qdir = (base or config.OUTPUT_ROOT) / "quality"
    df = pd.concat(
        [pd.read_csv(qdir / f"fiq_{ds}.csv") for ds in config.DATASETS],
        ignore_index=True,
    )
    out_dir = args.out_dir or config.output_dir("tables")
    out_dir.mkdir(parents=True, exist_ok=True)
    header = PAPER_HEADER if args.paper_header else HEADER
    (out_dir / "fiq_grid.tex").write_text(grid_table(df, args.shading, header))
    log.info("wrote %s", out_dir / "fiq_grid.tex")
    if not args.no_figure:
        fig_dir = args.fig_dir or config.output_dir("figures")
        log.info("wrote %s", figure(df, fig_dir / "fiq_by_codec.png"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
