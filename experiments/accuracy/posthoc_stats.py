"""Rank statistics of the codec ranking across matchers (Section 14.5).

From the matcher x codec EER matrix of ``accuracy/metrics.csv`` at Color FERET,
112 px, 1024 B (every matcher with an EER for all 12 codecs;
:func:`face1kb.eval.significance.eer_matrix`) this computes the Friedman test,
Kendall's W, the mean rank of every codec (1 = lowest EER) and, for eight headline
codec pairs, a Wilcoxon signed-rank test with Holm correction and Cliff's delta
(:func:`face1kb.eval.significance.posthoc`). Outputs:

* ``posthoc_stats.tex`` (``tab:posthoc``, under ``--out-dir``);
* ``accuracy/posthoc_scalars.txt`` (under ``--scalars-dir``): ``n``, ``k``,
  Friedman chi-square and p, Kendall's W and the mean ranks.

``--exclude-prefix edgeface`` drops the four EdgeFace matchers (the figure quoted
next to the table, W = 0.893 over 10 matchers); the outputs then get the suffix
``_excl_<prefix>``.

Examples
--------
    python experiments/accuracy/posthoc_stats.py --from-results --paper-header
    python experiments/accuracy/posthoc_stats.py --from-results \
        --exclude-prefix edgeface
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config

log = logging.getLogger("posthoc_stats")

HEADER = "% generated by experiments/accuracy/posthoc_stats.py"
PAPER_HEADER = "% generated by generate_posthoc_stats.py"
DATASET, RES, BUDGET = "colorferet", 112, 1024
NAME = {
    "jpeg_ai": "JPEG-AI",
    "jpeg": "JPEG",
    "jpeg2000": "JPEG 2000",
    "webp": "WebP",
    "jpeg_xl": "JPEG XL",
    "avif": "AVIF",
    "heif": "HEIF",
    "jpeg_fzt": "JPEG-FzT",
    "neural_bmshj2018": "bmshj2018",
    "neural_mbt2018_mean": "mbt2018",
    "ours_fast": "Ours-FAST",
    "ours_accurate": "Ours-ACCURATE",
}


def table(res: dict, header: str) -> str:
    """LaTeX tabular of the Holm-Wilcoxon / Cliff's delta pairs."""
    lines = [
        header,
        "\\begin{tabular}{llrrl}",
        "\\toprule",
        "Codec $a$ & Codec $b$ & Wilcoxon $p_{\\text{Holm}}$ "
        "& Cliff's $\\delta$ & sig.? \\\\",
        "\\midrule",
    ]
    for a, b, _, ph, d in res["pairs"]:
        sig = "yes" if ph < 0.05 else "\\textbf{no}"
        lines.append(f"{NAME[a]} & {NAME[b]} & {ph:.3g} & {d:+.2f} & {sig} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def scalars(res: dict) -> str:
    """Return the one-line summary and the mean ranks."""
    return (
        f"n={res['n']} k={res['k']} friedman_chi2={res['friedman_chi2']:.1f} "
        f"friedman_p={res['friedman_p']:.2e} kendall_w={res['kendall_w']:.3f}\n"
        + "mean_rank: "
        + ", ".join(f"{NAME[c]}={r:.2f}" for c, r in res["mean_rank"].items())
        + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    """Compute the statistics and write the table and the scalars file."""
    from face1kb.eval.significance import eer_matrix, posthoc  # noqa: PLC0415

    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--input-root", default=None, help="default: outputs/")
    src.add_argument(
        "--from-results", action="store_true", help="read the shipped results/"
    )
    ap.add_argument("--metrics", default=None, help="default: accuracy/metrics.csv")
    ap.add_argument(
        "--exclude-prefix", default=None, help="drop matchers, e.g. edgeface"
    )
    ap.add_argument("--out-dir", default=None, help="default: outputs/tables")
    ap.add_argument("--scalars-dir", default=None, help="default: outputs/accuracy")
    ap.add_argument(
        "--paper-header", action="store_true", help="comment line of the paper"
    )
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    root = (
        config.RESULTS_ROOT
        if args.from_results
        else Path(args.input_root or config.OUTPUT_ROOT)
    )
    df = pd.read_csv(Path(args.metrics or root / "accuracy" / "metrics.csv"))
    mat = eer_matrix(
        df, dataset=DATASET, res=RES, budget=BUDGET, exclude_prefix=args.exclude_prefix
    )
    res = posthoc(mat)
    log.info(
        "%d matchers x %d codecs: Friedman chi2=%.1f p=%.2e, Kendall W=%.3f",
        res["n"],
        res["k"],
        res["friedman_chi2"],
        res["friedman_p"],
        res["kendall_w"],
    )
    sfx = f"_excl_{args.exclude_prefix}" if args.exclude_prefix else ""
    out_dir = Path(args.out_dir) if args.out_dir else config.output_dir("tables")
    sc_dir = (
        Path(args.scalars_dir) if args.scalars_dir else config.output_dir("accuracy")
    )
    out_dir.mkdir(parents=True, exist_ok=True)
    sc_dir.mkdir(parents=True, exist_ok=True)
    header = PAPER_HEADER if args.paper_header else HEADER
    (out_dir / f"posthoc_stats{sfx}.tex").write_text(table(res, header))
    (sc_dir / f"posthoc_scalars{sfx}.txt").write_text(scalars(res))
    log.info("wrote %s", out_dir / f"posthoc_stats{sfx}.tex")
    log.info("wrote %s", sc_dir / f"posthoc_scalars{sfx}.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
