r"""LaTeX tables of the preprocessing and crop-tightness ablations.

From the aggregates of this area it writes, under ``OUTPUT_ROOT/tables``:

* ``preproc_through_codec.tex`` (ArcFace) and ``preproc_through_codec_edgeface.tex``
  (EdgeFace-XS), from ``accuracy/preproc_through_codec_kk.csv`` (rows with
  ``res == 224`` and ``budget == 1024``): operators x codec blocks of EER (%) and the
  reconstruction's identity cosine to the unprocessed crop. Per column the best and
  worst value is shaded (EER lower, id-cos higher is better; the ``std`` row takes
  part); a missing cell prints ``--``.
* ``ablation_croptightness.tex`` and ``ablation_preprocessing.tex``, from
  ``ablation/preprocessing_ablation.csv``: clean EER (%) per anchor matcher and, for
  the preprocessing table, the identity cosine to the standard crop averaged over the
  matchers. Ranking is on the printed value (2 decimals for EER, 3 for id-cos); ties
  at an extreme are all shaded, an all-tied column is not shaded, the ``std`` row's
  id-cos (1.000 by construction) is not ranked, and missing values print ``--``.

Shaded cells carry the bold (best) / underline (worst) marker of the paper tables.
``--from-results`` reads the shipped aggregates under ``results/``;
``--paper-header`` writes the comment lines of the published tables (the published
ArcFace through-codec table has none), which makes the output byte-identical to them
for the same inputs.

Examples
--------
    python experiments/preprocessing/make_tables.py
    python experiments/preprocessing/make_tables.py --from-results --paper-header
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import numpy as np
import pandas as pd

from face1kb import config
from face1kb.data.cli_utils import setup_logging
from face1kb.report.latex import shade_best, shade_worst

log = logging.getLogger("preprocessing_tables")

#: (codec, block label) of the through-codec tables.
THROUGH_CODECS: tuple[tuple[str, str], ...] = (
    ("webp", "WebP"),
    ("avif", "AVIF"),
    ("ours_accurate", "Ours-ACCURATE"),
)
#: (operator, row label) of the through-codec tables.
THROUGH_OPERATORS: tuple[tuple[str, str], ...] = (
    ("std", "std (none)"),
    ("A1", "A1 edge-pres."),
    ("A2", "A2 bilateral"),
    ("A3", "A3 chroma-red."),
    ("A4", "A4 NLM denoise"),
    ("B2", "B2 bg-flatten"),
)
#: (matcher, table stem) of the through-codec tables.
THROUGH_TABLES: tuple[tuple[str, str], ...] = (
    ("arcface_antelopev2", "preproc_through_codec"),
    ("edgeface_xs", "preproc_through_codec_edgeface"),
)
#: Anchor matchers of the clean-crop tables (column order and label).
ANCHORS: tuple[tuple[str, str], ...] = (
    ("arcface_antelopev2", "ArcFace"),
    ("lvface_l", "LVFace-L"),
    ("topofr_r100", "TopoFR-R100"),
    ("edgeface_xs", "EdgeFace-XS"),
)
#: (variant, row label) of the crop-tightness table.
CROPS: tuple[tuple[str, str], ...] = (
    ("standard", "standard ($\\approx$0.31)"),
    ("tight", "tight (0.40)"),
    ("mid", "mid (0.46)"),
    ("fill", "fill (0.52)"),
)
#: (variant, row label) of the clean preprocessing table.
PREPROC: tuple[tuple[str, str], ...] = (
    ("std", "\\texttt{std} (none)"),
    ("A1", "A1 edge-preserving, mild"),
    ("A2", "A2 bilateral, strong"),
    ("A3", "A3 chroma de-emphasis"),
    ("A4", "A4 non-local-means"),
    ("B1", "B1 background flatten (BiRefNet)"),
    ("B2", "B2 background flatten (MediaPipe)"),
    ("C1", "C1 B1\\,+\\,A1"),
    ("C2", "C2 foveated ROI"),
)
PAPER_HEADERS = {
    "preproc_through_codec": None,
    "preproc_through_codec_edgeface": (
        "% generated by generate_preproc_through_codec_tables.py"
    ),
    "ablation_croptightness": "% auto-generated by generate_preprocessing_ablation.py",
    "ablation_preprocessing": "% auto-generated by generate_preprocessing_ablation.py",
}
DEFAULT_HEADER = "% generated by experiments/preprocessing/make_tables.py"


def _header(stem: str, paper: bool) -> list[str]:
    if not paper:
        return [DEFAULT_HEADER]
    h = PAPER_HEADERS.get(stem)
    return [h] if h else []


# ------------------------------------------------------------ through the codec
def _cell(v: float, fmt: str, best: bool, worst: bool) -> str:
    s = fmt % v
    if best:
        return shade_best(s)
    if worst:
        return shade_worst(s)
    return s


def through_codec_table(df: pd.DataFrame, model: str, header: list[str]) -> str:
    """Operator x codec table of one matcher (EER % and id-cos per codec)."""
    sub = df[df.model == model]
    cols = []
    for codec, _ in THROUGH_CODECS:
        c = sub[sub.codec == codec].set_index("operator")
        cols.append(
            {
                op: (
                    float(c.loc[op, "eer"]) * 100,
                    float(c.loc[op, "id_cos_vs_original"]),
                )
                for op, _ in THROUGH_OPERATORS
                if op in c.index
            }
        )
    lines = [
        *header,
        "\\begin{tabular}{@{}l" + "cc" * len(THROUGH_CODECS) + "@{}}",
        "\\toprule",
        "Operator & "
        + " & ".join(f"\\multicolumn{{2}}{{c}}{{{lab}}}" for _, lab in THROUGH_CODECS)
        + " \\\\",
        "".join(
            f"\\cmidrule(lr){{{2 + i * 2}-{3 + i * 2}}}"
            for i in range(len(THROUGH_CODECS))
        ),
        " & " + " & ".join("EER\\,\\% & id-cos" for _ in THROUGH_CODECS) + " \\\\",
        "\\midrule",
    ]
    ext = []
    for col in cols:
        eers = [v[0] for v in col.values()]
        ids = [v[1] for v in col.values()]
        ext.append((min(eers), max(eers), max(ids), min(ids)) if col else (None,) * 4)
    for op, label in THROUGH_OPERATORS:
        cells = []
        for col, (be, we, bi, wi) in zip(cols, ext, strict=True):
            if op not in col:
                cells += ["--", "--"]
                continue
            e, i = col[op]
            cells.append(_cell(e, "%.2f", e == be, e == we))
            cells.append(_cell(i, "%.3f", i == bi, i == wi))
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------ clean crops
def _fmt(x: float, nd: int = 2) -> str:
    return "--" if not np.isfinite(x) else f"{x:.{nd}f}"


def shade_column(
    values: list[float],
    lower_better: bool = True,
    nd: int = 2,
    skip: set[int] | None = None,
) -> list[str]:
    """Format a column and shade its best / worst printed value."""
    skip = skip or set()
    values = [round(v, nd) if np.isfinite(v) else v for v in values]
    finite = [v for i, v in enumerate(values) if np.isfinite(v) and i not in skip]
    if len(set(finite)) < 2:
        return [_fmt(v, nd) for v in values]
    best = (min if lower_better else max)(finite)
    worst = (max if lower_better else min)(finite)
    out = []
    for i, v in enumerate(values):
        txt = _fmt(v, nd)
        if not np.isfinite(v) or i in skip:
            out.append(txt)
        elif v == best:
            out.append(shade_best(txt))
        elif v == worst:
            out.append(shade_worst(txt))
        else:
            out.append(txt)
    return out


def _value(df: pd.DataFrame, study: str, variant: str, model: str, col: str) -> float:
    r = df[(df.study == study) & (df.variant == variant) & (df.model == model)]
    return float(r[col].iloc[0]) if len(r) else float("nan")


def crop_table(df: pd.DataFrame, header: list[str]) -> str:
    """Clean EER (%) of the crop-tightness presets per anchor matcher."""
    head = " & ".join(lbl for _, lbl in ANCHORS)
    lines = [
        *header,
        "\\begin{tabular}{l" + "c" * len(ANCHORS) + "}",
        "\\toprule",
        f"Crop tightness (IOD/W) & {head} \\\\",
        "\\midrule",
    ]
    cols = [
        [_value(df, "crop", v, m, "eer") * 100.0 for v, _ in CROPS] for m, _ in ANCHORS
    ]
    shaded = [shade_column(c) for c in cols]
    for i, (_, lbl) in enumerate(CROPS):
        cells = " & ".join(shaded[j][i] for j in range(len(ANCHORS)))
        lines.append(f"{lbl} & {cells} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def mean_id_cos(df: pd.DataFrame, variant: str) -> float:
    """Identity cosine to the standard crop, averaged over the anchor matchers."""
    vals = [
        c
        for c in (
            _value(df, "preproc", variant, m, "id_cos_vs_std") for m, _ in ANCHORS
        )
        if np.isfinite(c)
    ]
    return float(np.mean(vals)) if vals else float("nan")


def preproc_table(df: pd.DataFrame, header: list[str]) -> str:
    """Clean EER (%) of the preprocessing operators plus mean id-cos vs std."""
    head = " & ".join(lbl for _, lbl in ANCHORS)
    lines = [
        *header,
        "\\begin{tabular}{l" + "c" * len(ANCHORS) + "c}",
        "\\toprule",
        f"Variant & \\multicolumn{{{len(ANCHORS)}}}{{c}}{{EER (\\%)}} & id-cos \\\\",
        "\\cmidrule(lr){2-" + str(len(ANCHORS) + 1) + "}",
        f" & {head} & vs.\\ std \\\\",
        "\\midrule",
    ]
    cols = [
        [_value(df, "preproc", v, m, "eer") * 100.0 for v, _ in PREPROC]
        for m, _ in ANCHORS
    ]
    shaded = [shade_column(c) for c in cols]
    cos_col = shade_column(
        [mean_id_cos(df, v) for v, _ in PREPROC],
        lower_better=False,
        nd=3,
        skip={i for i, (v, _) in enumerate(PREPROC) if v == "std"},
    )
    for i, (_, lbl) in enumerate(PREPROC):
        eers = " & ".join(shaded[j][i] for j in range(len(ANCHORS)))
        lines.append(f"{lbl} & {eers} & {cos_col[i]} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------ main
def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument(
        "--input-root",
        default=None,
        help="root holding accuracy/ and ablation/ (default: OUTPUT_ROOT)",
    )
    src.add_argument(
        "--from-results",
        action="store_true",
        help="read the shipped paper results (results/)",
    )
    ap.add_argument("--out-dir", default=None, help="default: OUTPUT_ROOT/tables")
    ap.add_argument(
        "--paper-header",
        action="store_true",
        help="use the comment lines of the published tables (byte-identical output)",
    )
    args = ap.parse_args(argv)
    setup_logging()
    if args.from_results:
        root = config.RESULTS_ROOT
    elif args.input_root:
        root = Path(args.input_root)
    else:
        root = config.OUTPUT_ROOT
    out_dir = Path(args.out_dir) if args.out_dir else config.output_dir("tables")
    written = []

    def write(stem: str, text: str) -> None:
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / f"{stem}.tex").write_text(text)
        written.append(stem)
        log.info("wrote %s", out_dir / f"{stem}.tex")

    through = root / "accuracy" / "preproc_through_codec_kk.csv"
    if through.exists():
        df = pd.read_csv(through)
        df = df[(df.res == 224) & (df.budget == 1024)]
        for model, stem in THROUGH_TABLES:
            write(
                stem, through_codec_table(df, model, _header(stem, args.paper_header))
            )
    else:
        log.warning("skip the through-codec tables: %s is missing", through)
    clean = root / "ablation" / "preprocessing_ablation.csv"
    if clean.exists():
        df = pd.read_csv(clean)
        stem = "ablation_croptightness"
        write(stem, crop_table(df, _header(stem, args.paper_header)))
        stem = "ablation_preprocessing"
        write(stem, preproc_table(df, _header(stem, args.paper_header)))
    else:
        log.warning("skip the clean-crop tables: %s is missing", clean)
    return 0 if written else 1


if __name__ == "__main__":
    raise SystemExit(main())
