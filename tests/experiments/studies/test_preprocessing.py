def _through_df():
    rows = []
    for codec in ("webp", "avif", "ours_accurate"):
        for k, op in enumerate(("std", "A1", "A2", "A3", "A4", "B2")):
            for model in ("arcface_antelopev2", "edgeface_xs"):
                rows.append(
                    {
                        "operator": op,
                        "codec": codec,
                        "res": 224,
                        "budget": 1024,
                        "model": model,
                        "eer": 0.004 + 0.001 * k,
                        "id_cos_vs_original": 0.9 - 0.01 * k,
                        "delta_eer_vs_std": 0.001 * k,
                        "n_images": 800,
                    }
                )
    return pd.DataFrame(rows)


def test_through_codec_table():
    df = _through_df()
    tex = tables.through_codec_table(df, "arcface_antelopev2", [])
    lines = tex.splitlines()
    assert lines[0].startswith("\\begin{tabular}{@{}lcccccc@{}}")
    std = next(ln for ln in lines if ln.startswith("std (none)"))
    assert std.count("\\cellcolor{green!25}\\textbf{") == 6  # best EER and id-cos
    b2 = next(ln for ln in lines if ln.startswith("B2 bg-flatten"))
    assert b2.count("\\cellcolor{red!22}\\underline{") == 6
    assert "0.40" in std and "0.900" in std
    # a missing operator prints --
    tex = tables.through_codec_table(df[df.operator != "A2"], "edgeface_xs", ["% h"])
    a2 = next(ln for ln in tex.splitlines() if ln.startswith("A2 bilateral"))
    assert a2.split(" & ")[1:3] == ["--", "--"]
    assert tex.splitlines()[0] == "% h"


