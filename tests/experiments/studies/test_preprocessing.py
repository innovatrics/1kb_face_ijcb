    out = pd.read_csv(config.output_dir("accuracy") / tc.OUT_NAME)
    assert list(out.columns) == list(tc.COLUMNS)
    assert len(out) == 2
    assert (out.n_images == 12).all()
    assert out.loc[out.operator == "std", "delta_eer_vs_std"].iloc[0] == 0.0
    cache = config.work_dir("kk") / "preproc_through_codec"
    assert (cache / "crops_n12_s0_A3_webp.npy").is_file()
    crops = np.load(cache / "crops_n12_s0_std_webp.npy")
    assert crops.shape == (12, 112, 112, 3) and crops.dtype == np.uint8
