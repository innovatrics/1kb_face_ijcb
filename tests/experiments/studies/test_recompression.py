def test_toy_run_produce_and_score(roots, toy_matcher, tmp_path):
    """End to end on a toy dataset: produce, resume, score, merge (CPU)."""
    from PIL import Image

    from face1kb.baselines import classical
    from face1kb.baselines import extension as ext

    ds, budget = "colorferet", 700
    index = make_dataset(ds, n_subjects=4, per_subject=3)
    # single-pass references of the second codecs
    for codec in ("webp", "jpeg"):
        for rel in index.rel_path:
            with Image.open(config.aligned_dir(ds, 112) / rel) as im:
                img = np.asarray(im.convert("RGB"))
            data, _ = classical.encode_to_budget(img, codec, budget)
            out = config.compressed_dir(ds, 112, budget, codec) / rel
            out = out.with_suffix(ext(codec))
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(data)
    args = [
        "--dataset",
        ds,
        "--budget",
        str(budget),
        "--sources",
        "jpeg,webp",
        "--seconds",
        "webp,jpeg",
        "--workers",
        "1",
        "--model",
        toy_matcher,
        "--device",
        "cpu",
        "--stages",
        "produce",
    ]
    assert rc.main(args) == 0
    root = rc.recompressed_root(ds)
    cell = rc.cell_dir(root, "jpeg", "webp", 112, budget)
    files = sorted(cell.rglob("*.webp"))
    assert len(files) == len(index)
    assert all(f.stat().st_size <= budget for f in files)
    mtimes = [f.stat().st_mtime_ns for f in files]
    manifest = root / "manifest" / f"jpeg__webp_112_{budget}.parquet"
    assert len(pd.read_parquet(manifest)) == len(index)
    assert rc.main(args) == 0  # resume: nothing rewritten
    assert [f.stat().st_mtime_ns for f in files] == mtimes

    args[-1] = "score"
    assert rc.main(args) == 0
    csv = rc.output_csv(config.output_dir("recompression"), ds, budget, toy_matcher)
    assert csv.name == f"recompression_{ds}_{toy_matcher}.csv"
    out = pd.read_csv(csv)
    assert list(out.columns) == list(rc.COLUMNS)
    assert len(out) == 4
    assert out.eer.between(0, 1).all()
    assert list(zip(out.source_codec, out.second_codec)) == [
        ("jpeg", "jpeg"),
        ("jpeg", "webp"),
        ("webp", "jpeg"),
        ("webp", "webp"),
    ]
    # rows already present are skipped; --rescore recomputes them identically
    assert rc.main([*args, "--rescore"]) == 0
    pd.testing.assert_frame_equal(out, pd.read_csv(csv))


