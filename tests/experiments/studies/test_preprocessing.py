def test_shade_column_rules():
    out = tables.shade_column([0.041, 0.044, 0.25, float("nan")])
    assert out[0].startswith("\\cellcolor{green!25}") and out[1].startswith(
        "\\cellcolor{green!25}"
    )  # tie at the printed value
    assert out[2].startswith("\\cellcolor{red!22}") and out[3] == "--"
    assert tables.shade_column([1.0, 1.001]) == ["1.00", "1.00"]  # all tied
    cos = tables.shade_column([1.0, 0.9, 0.8], lower_better=False, nd=3, skip={0})
    assert cos[0] == "1.000" and "green" in cos[1] and "red" in cos[2]


def _ablation_df():
    rows = []
    for study, variant, suffix in ab.VARIANTS:
        for j, (model, _) in enumerate(tables.ANCHORS):
            k = [v for _, v, _ in ab.VARIANTS].index(variant)
            rows.append(
                {
                    "study": study,
                    "variant": variant,
                    "suffix": suffix,
                    "model": model,
                    "eer": 0.0004 * (1 + k) * (1 + j),
                    "id_cos_vs_std": 1.0
                    if suffix == ""
                    else 0.9 - 0.01 * k - 0.001 * j,
                    "n_pos": 10,
                    "n_neg": 100,
                }
            )
    return pd.DataFrame(rows)


def test_clean_tables():
    df = _ablation_df()
    crop = tables.crop_table(df, []).splitlines()
    assert crop[0] == "\\begin{tabular}{lcccc}"
    assert crop[4].startswith("standard ($\\approx$0.31) & \\cellcolor{green!25}")
    pre = tables.preproc_table(df, []).splitlines()
    std = next(ln for ln in pre if ln.startswith("\\texttt{std}"))
    assert std.endswith("& 1.000 \\\\")  # std id-cos is printed, never ranked
    assert np.isclose(
        tables.mean_id_cos(df, "A1"),
        np.mean([0.9 - 0.01 * 5 - 0.001 * j for j in range(4)]),
    )


def test_id_cos():
    rng = np.random.default_rng(0)
    a = rng.normal(size=(20, 8)).astype(np.float32)
    assert np.isclose(ab.id_cos(a, a), 1.0)
    b = a.copy()
    b[3] = np.nan
    assert np.isclose(ab.id_cos(a, b), 1.0)
    assert np.isnan(ab.id_cos(None, a))
    assert np.isclose(ab.id_cos(a, -a), -1.0)


def test_ablation_rows_on_toy_embeddings(roots):
    make_dataset("colorferet", n_subjects=5, per_subject=4)
    n = 20
    subj = np.repeat(np.arange(5), 4)
    rng = np.random.default_rng(1)
    centres = rng.normal(size=(5, 512)).astype(np.float32)
    for suffix, noise in (("", 0.05), ("_tight", 0.5), ("_A1", 3.0)):
        emb = centres[subj] + noise * rng.normal(size=(n, 512)).astype(np.float32)
        path = config.embeddings_path(
            "colorferet", "arcface_antelopev2", config.embedding_tag(112, suffix)
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        np.save(path, emb.astype(np.float32))
    from face1kb.eval import verification

    pairs = verification.pair_indices("colorferet", 0, 0)
    rows = pd.DataFrame(ab.ablation_rows(["arcface_antelopev2"], pairs))
    assert len(rows) == len(ab.VARIANTS)
    by = rows.set_index(["study", "variant"])
    assert by.loc[("crop", "standard"), "eer"] == 0.0
    assert by.loc[("crop", "standard"), "eer"] == by.loc[("preproc", "std"), "eer"]
    assert by.loc[("preproc", "A1"), "eer"] > by.loc[("crop", "tight"), "eer"]
    assert np.isnan(by.loc[("crop", "fill"), "eer"])  # no embedding array
    assert by.loc[("preproc", "std"), "id_cos_vs_std"] == 1.0
    assert (by.n_pos[by.eer.notna()] == 30).all()


def test_webp_descending_scan():
    rng = np.random.default_rng(0)
    img = rng.integers(0, 256, size=(112, 112, 3), dtype=np.uint8)
    dec, nbytes, q = impact.webp_descending(img, 1024)
    assert dec.shape == img.shape
    assert q in impact.QUALITIES
    assert nbytes <= 1024 or q == 2
    if q != 94:  # the next quality up does not fit
        from face1kb.baselines import classical

        assert len(classical.encode_setting(img, "webp", q + 2)) > 1024


def test_through_codec_toy_run(roots, toy_matcher, monkeypatch):
    """encode + aggregate on a toy KK set with WebP (CPU)."""
    pytest.importorskip("cv2")
    make_dataset("kk", n_subjects=4, per_subject=4, resolutions=(224,))
    args = [
        "--n",
        "12",
        "--operators",
        "std,A3",
        "--codecs",
        "webp",
        "--models",
        toy_matcher,
        "--device",
        "cpu",
    ]
