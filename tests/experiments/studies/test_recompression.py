def _rel(n_subj, per):
    return [f"{s:05d}/{s:05d}_{k:02d}.png" for s in range(n_subj) for k in range(per)]


def test_subject_spread_sample():
    rel = _rel(40, 12)
    s = rc.subject_spread_sample(rel, 120, 10)
    assert len(s) == 120 and np.all(np.diff(s) > 0)
    subjects = {rel[i].split("/")[0] for i in s}
    # stride 40 * 10 // 120 = 3 -> subjects 0, 3, 6, ... with 10 crops each
    assert subjects == {f"{k:05d}" for k in range(0, 36, 3)}
    assert all(int(rel[i].split("_")[1][:2]) < 10 for i in s)
    # a short strided pass is topped up from the remaining subjects
    small = rc.subject_spread_sample(_rel(3, 2), 5, 10)
    assert len(small) == 5
    assert np.array_equal(rc.subject_spread_sample(rel, 120, 10), s)


def test_restrict_pairs():
    i1 = np.array([0, 0, 1, 2, 3])
    i2 = np.array([1, 2, 2, 3, 4])
    lab = np.array([1, 0, 1, 0, 1])
    (p1, p2), (n1, n2) = rc.restrict_pairs(i1, i2, lab, np.array([0, 1, 2]), 5)
    assert list(zip(p1, p2)) == [(0, 1), (1, 2)]
    assert list(zip(n1, n2)) == [(0, 2)]


def _row(src, dst, eer, budget=1024):
    return rc._row("colorferet", 112, budget, src, dst, eer, 0.0)


def test_merge_rows_replace_and_order():
    rows = [_row("ours_accurate", "jpeg", 0.3), _row("webp", "jpeg", 0.1)]
    df = rc.merge_rows(None, rows)
    assert list(df.source_codec) == ["webp", "ours_accurate"]
    df = rc.merge_rows(df, [_row("webp", "jpeg", 0.2), _row("jpeg", "webp", 0.4)])
    assert list(zip(df.source_codec, df.second_codec)) == [
        ("jpeg", "webp"),
        ("webp", "jpeg"),
        ("ours_accurate", "jpeg"),
    ]
    assert df.loc[1, "eer"] == 0.2
    assert tuple(df.columns) == rc.COLUMNS


def _matrix_df(eer):
    rows = []
    for s in rc.MATRIX:
        for d in rc.MATRIX:
            rows.append(_row(s, d, eer(s, d)))
    return pd.DataFrame(rows)


def test_table_shading_rules():
    order = list(rc.MATRIX)

    def eer(s, d):
        if d == "webp" and s in ("jpeg", "avif"):
            return 0.001  # tie at the best printed value
        if d == "heif":
            return 0.05  # all tied -> unshaded
        if s == "ours_accurate":
            return 0.0001  # confounded: never ranked
        return 0.01 + 0.001 * order.index(s) + 0.0001 * order.index(d)

    df = _matrix_df(eer)
    tex = tables.render(df, "recompression_eer_colorferet_1024", tables.PAPER_HEADER)
    lines = tex.splitlines()
    assert lines[0] == "% generated by generate_recompression_tables.py"
    body = {ln.split(" & ")[0]: ln.split(" & ")[1:] for ln in lines if " & " in ln}
    col = {c: i for i, c in enumerate(order)}
    webp = [body[lab][col["webp"]] for _, lab in tables.CODECS]
    assert webp[col["jpeg"]].startswith("\\cellcolor{green!25}\\textbf{")
    assert webp[col["avif"]].startswith("\\cellcolor{green!25}\\textbf{")
    assert webp[col["jpeg_fzt"]].startswith("\\cellcolor{red!22}\\underline{")
    heif = [body[lab][col["heif"]] for _, lab in tables.CODECS]
    assert not any("cellcolor" in c for c in heif)
    assert not any("cellcolor" in c for c in body["Ours-ACC"])
    ours_col = [body[lab][col["ours_accurate"]] for _, lab in tables.CODECS]
    assert not any("cellcolor" in c for c in ours_col)


