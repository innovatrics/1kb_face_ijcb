def _summary(rows):
    out = []
    for ds, res, b, codec, n, pct in rows:
        s = np.full(n, b) if pct == 100 else np.r_[np.full(n - 1, b), b + 1]
        r = sizes.summary_row(ds, res, b, codec, s)
        r["pct_holding"] = pct
        out.append(r)
    return pd.DataFrame(out)


def test_summary_row_statistics():
    r = sizes.summary_row("kk", 112, 512, "webp", [500, 510, 520, 530])
    assert (r["n"], r["min"], r["max"], r["median"]) == (4, 500, 530, 515.0)
    assert r["pct_holding"] == 50.0 and r["over_budget_pct"] == 50.0


def test_fit_table_rules():
    df = _summary(
        [
            ("kk", 64, 1024, "jpeg", 100, 100.0),
            ("kk", 64, 1024, "webp", 100, 99.6),  # rounds to 100: a tie, no shading
            ("kk", 96, 1024, "jpeg", 100, 90.0),
            ("kk", 96, 1024, "webp", 100, 80.4),
            ("kk", 96, 1024, "ours_accurate", 100, 99.0),
            ("kk", 64, 1024, "neural_bmshj2018", 3, 33.3),  # below MIN_N: dropped
        ]
    )
    tex = sizes.fit_table(df, "kk", 1024, [64, 96])
    lines = tex.splitlines()
    assert lines[0] == "% generated by generate_file_size_boxplots.py"
    assert "bmshj2018" not in tex  # a codec with no reported cell is left out
    assert "JPEG & 100 & 90 \\\\" in lines
    assert "WebP & 100 & \\cellcolor{red!22}80 \\\\" in lines
    assert "Ours-ACC & -- & \\cellcolor{green!25}99 \\\\" in lines  # unique max


def test_fit_table_green_needs_unique_max():
    df = _summary(
        [
            ("colorferet", 112, 512, "jpeg", 50, 100.0),
            ("colorferet", 112, 512, "heif", 50, 100.0),
            ("colorferet", 112, 512, "avif", 50, 93.0),
        ]
    )
    tex = sizes.fit_table(df, "colorferet", 512, [112])
    assert "green" not in tex and "AVIF & \\cellcolor{red!22}93" in tex


def test_speed_table_shading_and_order():
    rows = [
        ("jpeg", "cpu", 112, 1024, 993, 0.26, 0.27),
        ("jpeg_fzt", "cpu", 112, 1024, 1075, 3.71, 30.5),
        ("ours_fast", "cpu", 112, 1024, 1007, 37.9, 52.0),
        ("ours_fast", "gpu", 112, 1024, 1007, 22.4, 22.9),
        ("ours_fast", "gpu", 112, 1024, 999, 1.0, 1.0),  # shadowed: first row wins
        ("neural_bmshj2018", "gpu", 112, 1024, 224, 7.61, 9.56),
    ]
    df = pd.DataFrame(
        rows,
        columns=[
            "codec",
            "device",
            "res",
            "budget",
            "median_bytes",
            "enc_median_ms",
            "dec_median_ms",
        ],
    )
    lines = speed.speed_table(df).splitlines()
    body = lines[lines.index("\\midrule") + 1 : lines.index("\\bottomrule")]
    assert [ln.split(" & ")[0] for ln in body] == [
        "JPEG",
        "JPEG-FzT",
        "bmshj2018",
        "Ours-FAST",
    ]
    assert body[0] == (
        "JPEG & 993 & \\cellcolor{green!25}0.26 & \\cellcolor{green!25}0.27 "
        "& -- & -- & -- \\\\"
    )
    assert "cellcolor" not in body[1]  # JPEG-FzT is neither fastest nor slowest
    assert body[3].endswith(
        "& 1007 & \\cellcolor{red!22}22.4 & \\cellcolor{red!22}22.9 \\\\"
    )
    assert "993" not in body[3]
    assert speed.fmt_ms(172.4) == "172" and speed.fmt_ms(17.74) == "17.7"


