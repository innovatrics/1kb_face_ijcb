r"""Pairwise significance tables (Sections 14.2 and 14.4).

Reads ``accuracy/significance_<dataset>.csv`` (``compute_significance.py``) and
writes

* ``sig_cf_edgeface.tex`` (``tab:sig-cf-edgeface``): a fixed list of 21 codec pairs
  of the Color FERET / EdgeFace-XS / 112 px / 1024 B cell in four blocks (the
  aligned reference against codecs, pairs involving JPEG 2000 and the modern codecs,
  close pairs, and the Ours variants); the numbers come from the CSV;
* ``sig_kk.tex`` (``tab:sig-kk``): per AI-Solutions-KK cell (anchor x resolution)
  every pair that is not significant after BH-FDR, plus two reference contrasts --
  the significant pair with the largest McNemar chi-square, and the one involving
  the aligned reference -- ordered by significance and chi-square.

Columns: McNemar chi-square, AUC of both codecs, BH-adjusted p and the verdict at
p_adj < 0.05.

Examples
--------
    python experiments/accuracy/significance_tables.py --from-results --paper-header
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import pandas as pd

from face1kb import config

log = logging.getLogger("significance_tables")

HEADER = "% generated by experiments/accuracy/significance_tables.py"
PAPER_HEADER = "% generated by generate_significance_tables.py"
LABEL = {
    "aligned": "aligned",
    "avif": "avif",
    "heif": "heif",
    "jpeg": "jpeg",
    "jpeg2000": "jpeg2000",
    "jpeg_ai": "jpeg\\_ai",
    "jpeg_fzt": "jpeg\\_fzt",
    "jpeg_xl": "jpeg\\_xl",
    "ours_accurate": "ours\\_accurate",
    "ours_fast": "ours\\_fast",
    "webp": "webp",
}
ANCHOR = {
    "arcface_antelopev2": "ArcFace",
    "lvface_l": "LVFace-L",
    "topofr_r100": "TopoFR-R100",
    "edgeface_xs": "EdgeFace-XS",
}
#: Pair blocks of the Color FERET / EdgeFace-XS table.
CURATED_CF = [
    [("aligned", c) for c in ("avif", "jpeg", "jpeg2000", "jpeg_ai", "webp")],
    [
        ("avif", "jpeg2000"),
        ("jpeg", "jpeg2000"),
        ("avif", "heif"),
        ("jpeg_ai", "jpeg_xl"),
        ("avif", "jpeg_ai"),
        ("jpeg_ai", "webp"),
    ],
    [
        ("avif", "webp"),
        ("heif", "jpeg_xl"),
        ("heif", "ours_fast"),
        ("jpeg_xl", "ours_fast"),
    ],
    [
        ("aligned", "ours_accurate"),
        ("aligned", "ours_fast"),
        ("ours_accurate", "ours_fast"),
        ("jpeg2000", "ours_accurate"),
        ("avif", "ours_accurate"),
        ("jpeg_ai", "ours_accurate"),
    ],
]
CURATED_CELL = ("colorferet", "edgeface_xs", 112, 1024)


def _p(v) -> str:
    """Format an adjusted p: approx. 0, scientific below 1e-3, else 3 decimals."""
    if v <= 0:
        return "$\\approx 0$"
    if v < 1e-3:
        m, e = f"{v:.1e}".split("e")
        return f"${m}\\times10^{{{int(e)}}}$"
    return f"{v:.3f}"


def _chi(v) -> str:
    return f"{v:.2f}" if v < 10 else f"{v:,.1f}"


def _find(cell, a, b):
    """Row of the pair ``(a, b)`` in either stored order, and whether it is flipped."""
    r = cell[(cell.codec_a == a) & (cell.codec_b == b)]
    if not r.empty:
        return r.iloc[0], False
    r = cell[(cell.codec_a == b) & (cell.codec_b == a)]
    return (r.iloc[0], True) if not r.empty else (None, False)


def curated_table(df: pd.DataFrame, header: str) -> str:
    """Build the Color FERET / EdgeFace-XS table ('' when the cell is missing)."""
    ds, model, res, budget = CURATED_CELL
    cell = df[
        (df.dataset == ds)
        & (df.model == model)
        & (df.res == res)
        & (df.budget == budget)
    ]
    if cell.empty:
        return ""
    lines = [
        header,
        "\\begin{tabular}{llrrrrl}",
        "\\toprule",
        "Codec $a$ & Codec $b$ & McNemar $\\chi^2$ & AUC$_a$ & AUC$_b$ "
        "& $p_\\mathrm{adj}$ & sig.? \\\\",
        "\\midrule",
    ]
    for i, block in enumerate(CURATED_CF):
        if i:
            lines.append("    \\midrule")
        for a, b in block:
            r, flip = _find(cell, a, b)
            if r is None:
                log.warning("pair %s vs %s missing", a, b)
                continue
            auc_a, auc_b = (r.auc_b, r.auc_a) if flip else (r.auc_a, r.auc_b)
            verdict = "yes" if r.significant else "\\textbf{no}"
            lines.append(
                f"    {LABEL.get(a, a)} & {LABEL.get(b, b)} & {_chi(r.mcnemar_chi2)} "
                f"& {auc_a:.4f} & {auc_b:.4f} & {_p(r.p_adj)} & {verdict} \\\\"
            )
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def _rows_for(cell: pd.DataFrame) -> pd.DataFrame:
    """Non-significant pairs plus the two reference contrasts, in reading order."""
    keep = list(cell[~cell.significant.astype(bool)].index)
    sig = cell[cell.significant.astype(bool)]
    if not sig.empty:
        keep.append(sig.mcnemar_chi2.idxmax())
        ali = sig[(sig.codec_a == "aligned") | (sig.codec_b == "aligned")]
        if not ali.empty:
            keep.append(ali.mcnemar_chi2.idxmax())
    order = list(dict.fromkeys(keep))
    return cell.loc[order].sort_values(["significant", "mcnemar_chi2"])


def dataset_table(df: pd.DataFrame, dataset: str, header: str) -> str:
    """One block per (anchor, resolution) cell of ``dataset``."""
    sub = df[df.dataset == dataset]
    lines = [
        header,
        "\\begin{tabular}{lllrrrrl}",
        "\\toprule",
        "Anchor & Codec $a$ & Codec $b$ & McNemar $\\chi^2$ & AUC$_a$ & AUC$_b$ "
        "& $p_\\mathrm{adj}$ & sig.? \\\\",
        "\\midrule",
    ]
    cells = sorted(sub.groupby(["model", "res"]).groups)
    several_res = len({r for _, r in cells}) > 1
    for k, (model, res) in enumerate(cells):
        rows = _rows_for(sub[(sub.model == model) & (sub.res == res)])
        head = ANCHOR.get(model, model) + (f", {res}\\,px" if several_res else "")
        lines.append(f"    \\multirow{{{len(rows)}}}{{*}}{{{head}}}")
        for _, r in rows.iterrows():
            verdict = "yes" if r.significant else "\\textbf{no}"
            lines.append(
                f"      & {LABEL.get(r.codec_a, r.codec_a)} "
                f"& {LABEL.get(r.codec_b, r.codec_b)} "
                f"& {_chi(r.mcnemar_chi2)} & {r.auc_a:.4f} & {r.auc_b:.4f} "
                f"& {_p(r.p_adj)} & {verdict} \\\\"
            )
        if k < len(cells) - 1:
            lines.append("    \\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write both significance tables."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument("--input-root", default=None, help="default: outputs/")
    src.add_argument(
        "--from-results", action="store_true", help="read the shipped results/"
    )
    ap.add_argument("--out-dir", default=None, help="default: outputs/tables")
    ap.add_argument(
        "--paper-header", action="store_true", help="comment line of the paper"
    )
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    root = (
        config.RESULTS_ROOT
        if args.from_results
        else Path(args.input_root or config.OUTPUT_ROOT)
    )
    out_dir = Path(args.out_dir) if args.out_dir else config.output_dir("tables")
    out_dir.mkdir(parents=True, exist_ok=True)
    header = PAPER_HEADER if args.paper_header else HEADER
    status = 0
    for ds, stem, build in (
        ("colorferet", "sig_cf_edgeface", curated_table),
        ("kk", "sig_kk", lambda d, h: dataset_table(d, "kk", h)),
    ):
        path = root / "accuracy" / f"significance_{ds}.csv"
        if not path.is_file():
            log.error("missing %s", path)
            status = 1
            continue
        df = pd.read_csv(path)
        tex = build(df, header)
        if not tex:
            log.error("%s: no rows for the table", path)
            status = 1
            continue
        (out_dir / f"{stem}.tex").write_text(tex)
        n_ns = int((~df.significant.astype(bool)).sum())
        log.info("wrote %s (%d of %d pairs not significant)", stem, n_ns, len(df))
    return status


if __name__ == "__main__":
    raise SystemExit(main())
