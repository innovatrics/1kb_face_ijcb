r"""Rate--identity codec-comparison tables (CPU).

Merges two aggregates:

* identity cosine (``id_cos``) from ``<input-root>/codec_comparison/res<res>/
  comparison.json`` -- medians over the 64-crop sample of ``evaluate.py``, measured at
  the 112 px matcher input;
* PSNR, SSIM and LPIPS at the codec's native resolution from
  ``<input-root>/quality/quality_summary.csv`` (``measure_quality.py``).

The ``id_cos`` values of the published ``comparison.json`` files were measured with a
proprietary face matcher that is not distributed; those shipped files
(``--from-results``) are the only source of the paper's id-cos columns. A
``comparison.json`` regenerated with ``evaluate.py`` holds the id-cos of the matcher
chosen there (a public model by default) and yields different numbers.

Outputs (``--out-dir``, default ``$FACE1KB_OUTPUT_ROOT/tables``):

* ``codec_comparison_{112,224}.tex`` (tab:codec-cmp-112/-224): id-cos, PSNR, SSIM
  and LPIPS per (budget, dataset) block, codecs sorted by id-cos;
* ``codec_results.tex`` (224 px) and ``codec_results_112.tex`` (tab:codec-results,
  tab:codec-results-112): id-cos and PSNR at 1024 and 512 B.

Best / worst per column and block are shaded green / red (LPIPS: lower is better).
Codecs without data for a cell are omitted.

Examples
--------
    python experiments/codec_comparison/tables.py --from-results
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
from pathlib import Path

from face1kb import config
from face1kb.data.cli_utils import setup_logging
from face1kb.report import latex

log = logging.getLogger("codec_comparison.tables")

#: Roster and labels, in the fallback order (sorting is by id-cos).
CODECS = (
    ("jpeg_ai", "JPEG-AI"),
    ("ours_accurate", "Ours-ACCURATE"),
    ("ours_fast", "Ours-FAST"),
    ("avif", "AVIF"),
    ("webp", "WebP"),
    ("jpeg_xl", "JPEG XL"),
    ("heif", "HEIF"),
    ("jpeg_fzt", "JPEG-FzT"),
    ("neural_mbt2018_mean", "mbt2018"),
    ("neural_bmshj2018", "bmshj2018"),
    ("jpeg", "JPEG"),
    ("jpeg2000", "JPEG 2000"),
)
DATASETS = (("colorferet", "Color~FERET"), ("kk", "KK"))
BUDGETS = (1024, 512)
#: (key, format, higher is better)
METRICS = (
    ("id_cos", "%.3f", True),
    ("psnr", "%.1f", True),
    ("ssim", "%.3f", True),
    ("lpips", "%.3f", False),
)
RESOLUTIONS = (112, 224)
#: First comment line of the generated tables and of the published copies.
HEADER = "% generated by experiments/codec_comparison/tables.py"
PAPER_HEADER = "% generated by generate_codec_comparison_tables.py"


def load_quality(path: Path, res: int) -> dict:
    """``{(dataset, budget, codec): {psnr, ssim, lpips}}`` at ``res`` from a summary."""
    out: dict = {}
    if not path.exists():
        log.warning("%s not found: fidelity columns print as --", path)
        return out
    with path.open() as fh:
        for row in csv.DictReader(fh):
            if int(float(row["res"])) != res:
                continue
            key = (row["dataset"], int(float(row["budget"])), row["codec"])
            out[key] = {
                m: (float(row[m]) if row.get(m) not in (None, "") else None)
                for m in ("psnr", "ssim", "lpips")
            }
    return out


def load(root: Path, res: int) -> dict:
    """id-cos from comparison.json merged with the native-resolution fidelity."""
    rows = json.loads(
        (root / "codec_comparison" / f"res{res}" / "comparison.json").read_text()
    )
    qual = load_quality(root / "quality" / "quality_summary.csv", res)
    merged: dict = {}
    for r in rows:
        key = (r["dataset"], r["budget"], r["codec"])
        q = qual.get(key, {})
        merged[key] = {
            **r,
            "psnr": q.get("psnr"),
            "ssim": q.get("ssim"),
            "lpips": q.get("lpips"),
        }
    return merged


def _extremes(rows, key: str, higher_better: bool):
    vals = [(c, r[key]) for c, r in rows if r.get(key) is not None]
    if len(vals) < 2:
        return None, None
    best = (max if higher_better else min)(vals, key=lambda x: x[1])[0]
    worst = (min if higher_better else max)(vals, key=lambda x: x[1])[0]
    return best, worst


def _cell(val, fmt: str, shade: str | None) -> str:
    if val is None:
        return "--"
    s = fmt % val
    if shade == "best":
        return latex.shade_best(s, emphasis=False)
    if shade == "worst":
        return latex.shade_worst(s, emphasis=False)
    return s


def comparison_table(data: dict, header: str = HEADER) -> str:
    """Per-resolution comparison table (id-cos, PSNR, SSIM, LPIPS)."""
    lines = [
        header,
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Dataset & Codec & id-cos$\\uparrow$ & PSNR$\\uparrow$ & SSIM$\\uparrow$ "
        "& LPIPS$\\downarrow$ \\\\",
        "\\midrule",
    ]
    disp = dict(CODECS)
    for budget in BUDGETS:
        lines.append(f"\\multicolumn{{6}}{{l}}{{\\emph{{Budget ${budget}$\\,B}}}}\\\\")
        for ds, ds_label in DATASETS:
            present = [
                (c, data[(ds, budget, c)]) for c, _ in CODECS if (ds, budget, c) in data
            ]
            present.sort(key=lambda cr: cr[1].get("id_cos", -9), reverse=True)
            shades = {k: _extremes(present, k, hb) for k, _f, hb in METRICS}
            for c, r in present:
                cells = []
                for key, fmt, _hb in METRICS:
                    best, worst = shades[key]
                    sh = "best" if c == best else "worst" if c == worst else None
                    cells.append(_cell(r[key], fmt, sh))
                lines.append(f"{ds_label} & {disp[c]} & " + " & ".join(cells) + " \\\\")
        if budget != BUDGETS[-1]:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def results_table(data: dict, header: str = HEADER) -> str:
    """Results table: id-cos and PSNR at 1024 and 512 B per dataset block."""
    cols = [(1024, "id_cos"), (1024, "psnr"), (512, "id_cos"), (512, "psnr")]
    lines = [
        header,
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "& & \\multicolumn{2}{c}{$1024$\\,B} & \\multicolumn{2}{c}{$512$\\,B} \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
        "Dataset & Codec & id-cos & PSNR & id-cos & PSNR \\\\",
        "\\midrule",
    ]
    for di, (ds, ds_label) in enumerate(DATASETS):
        present = [
            (c, lab)
            for c, lab in CODECS
            if (ds, 1024, c) in data or (ds, 512, c) in data
        ]
        present.sort(
            key=lambda cl: data[(ds, 1024, cl[0])].get("id_cos", -9)
            if (ds, 1024, cl[0]) in data
            else -9,
            reverse=True,
        )
        shade = {}
        for b, key in cols:  # all columns are higher-is-better
            vv = [
                (c, data[(ds, b, c)][key])
                for c, _ in present
                if (ds, b, c) in data and data[(ds, b, c)].get(key) is not None
            ]
            if len(vv) >= 2:
                shade[(b, key)] = (
                    max(vv, key=lambda x: x[1])[0],
                    min(vv, key=lambda x: x[1])[0],
                )
        for c, lab in present:
            cells = []
            for b, key in cols:
                if (ds, b, c) not in data:
                    cells.append("--")
                    continue
                fmt = "%.3f" if key == "id_cos" else "%.1f"
                best, worst = shade.get((b, key), (None, None))
                sh = "best" if c == best else "worst" if c == worst else None
                cells.append(_cell(data[(ds, b, c)][key], fmt, sh))
            lines.append(f"{ds_label} & {lab} & " + " & ".join(cells) + " \\\\")
        if di != len(DATASETS) - 1:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write the four codec-comparison tables."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument(
        "--input-root",
        type=Path,
        default=None,
        help="folder holding codec_comparison/ and quality/ "
        "(default: $FACE1KB_OUTPUT_ROOT)",
    )
    src.add_argument("--from-results", action="store_true", help="read <repo>/results")
    ap.add_argument(
        "--paper-header",
        action="store_true",
        help="write the first comment line of the published tables",
    )
    ap.add_argument("--out-dir", type=Path, default=None)
    args = ap.parse_args(argv)
    setup_logging()

    base = config.RESULTS_ROOT if args.from_results else args.input_root
    root = base or config.OUTPUT_ROOT
    out_dir = args.out_dir or config.output_dir("tables")
    out_dir.mkdir(parents=True, exist_ok=True)
    data = {res: load(root, res) for res in RESOLUTIONS}
    hdr = PAPER_HEADER if args.paper_header else HEADER
    outputs = {
        f"codec_comparison_{res}": comparison_table(data[res], hdr)
        for res in RESOLUTIONS
    }
    outputs["codec_results"] = results_table(data[224], hdr)
    outputs["codec_results_112"] = results_table(data[112], hdr)
    for stem, tex in outputs.items():
        (out_dir / f"{stem}.tex").write_text(latex.finalize_table(stem, tex))
        log.info("wrote %s", out_dir / f"{stem}.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
