r"""Tables and predictor figure of the sample-difficulty study (from aggregates).

Reads the aggregates of ``analyze.py`` (``difficulty/difficulty_correlations.csv``,
``difficulty/difficulty_contrast.csv``) and writes

* ``tables/difficulty_predictors.tex`` -- image-level Spearman rho between difficulty
  and each descriptor / attribute per dataset (sign, 2 decimals; ``*`` p < 0.05,
  ``**`` p < 0.01; bold when |rho| >= 0.30; ``--`` when undefined);
* ``tables/difficulty_contrast.tex`` -- Color FERET easiest vs. hardest decile means
  (3 significant digits), their ratio, and the glasses counts with a two-sided
  Fisher exact test;
* ``figures/difficulty_predictors.png`` -- the Color FERET predictor ranking.

``--from-results`` reads the shipped paper aggregates (``results/difficulty``);
``--paper-header`` writes the first comment line of the published tables, which makes
the output byte-identical to them for the paper aggregates.

Examples
--------
    python experiments/difficulty/make_tables.py
    python experiments/difficulty/make_tables.py --from-results --paper-header
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

import numpy as np
import pandas as pd

from face1kb import config
from face1kb.data.cli_utils import setup_logging

log = logging.getLogger("difficulty_tables")

DESCRIPTORS: tuple[tuple[str, str], ...] = (
    ("hf_share", "High-freq.\\ DCT share"),
    ("lap_var", "Laplacian var.\\ (detail)"),
    ("grad_mag", "Gradient magnitude"),
    ("edge_density", "Edge density"),
    ("entropy", "Grey-level entropy"),
    ("contrast", "Contrast (luma std)"),
    ("colorfulness", "Colorfulness"),
    ("brightness", "Brightness (luma mean)"),
)
CF_ATTRIBUTES: tuple[tuple[str, str], ...] = (
    ("abs_yaw", "$|$yaw$|$ (non-frontal)"),
    ("glasses", "Glasses"),
    ("beard", "Beard"),
    ("mustache", "Mustache"),
)
KK_ATTRIBUTES: tuple[tuple[str, str], ...] = (
    ("mst_index", "Monk skin-tone index"),
    ("age", "Age"),
)
CONTRAST: tuple[tuple[str, str], ...] = (
    ("hf_share", "High-freq.\\ share"),
    ("lap_var", "Laplacian var."),
    ("abs_yaw", "$|$yaw$|$ (deg)"),
    ("brightness", "Brightness"),
    ("contrast", "Contrast"),
)
HEADER = "% generated by experiments/difficulty/make_tables.py"
PAPER_HEADER = "% generated by generate_sample_difficulty.py"


def _num(v) -> float:
    try:
        return float(v)
    except (TypeError, ValueError):
        return float("nan")


def _fmt_rho(rec: pd.Series | None, ds: str) -> str:
    if rec is None:
        return "--"
    v, p = _num(rec.get(ds)), _num(rec.get(f"{ds}_p"))
    if np.isnan(v):
        return "--"
    star = "$^{**}$" if p < 0.01 else ("$^{*}$" if p < 0.05 else "")
    s = f"{v:+.2f}{star}"
    return f"\\textbf{{{s}}}" if abs(v) >= 0.30 else s


def predictors_table(corr: pd.DataFrame, header: str = HEADER) -> str:
    """``difficulty_predictors.tex`` from ``difficulty_correlations.csv``."""
    by_key = {r["key"]: r for _, r in corr.iterrows()}
    ns = [
        int(_num(by_key[k].get(f"{ds}_n")))
        for k, _ in DESCRIPTORS
        for ds in ("colorferet", "kk")
        if k in by_key and np.isfinite(_num(by_key[k].get(f"{ds}_n")))
    ]
    n = max(ns) if ns else 0
    lines = [
        header,
        f"% image-level Spearman (one point per image, n={n}/dataset); "
        "* p<0.05, ** p<0.01",
        "\\begin{tabular}{lrr}",
        "\\toprule",
        "Image property (codec-independent) & \\multicolumn{2}{c}{Spearman $\\rho$ "
        "vs.\\ difficulty} \\\\",
        "\\cmidrule(lr){2-3}",
        " & Color~FERET & AI-Solutions-KK \\\\",
        "\\midrule",
    ]
    for key, lab in DESCRIPTORS:
        rec = by_key.get(key)
        lines.append(
            f"{lab} & {_fmt_rho(rec, 'colorferet')} & {_fmt_rho(rec, 'kk')} \\\\"
        )
    lines.append("\\midrule")
    lines.append("\\multicolumn{3}{l}{\\emph{Face attributes (dataset-specific)}}\\\\")
    for key, lab in CF_ATTRIBUTES:
        if key in by_key:
            lines.append(f"{lab} & {_fmt_rho(by_key[key], 'colorferet')} & -- \\\\")
    for key, lab in KK_ATTRIBUTES:
        if key in by_key:
            lines.append(f"{lab} & -- & {_fmt_rho(by_key[key], 'kk')} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def contrast_table(con: pd.DataFrame, header: str = HEADER) -> str:
    """``difficulty_contrast.tex`` from ``difficulty_contrast.csv``."""
    from scipy.stats import fisher_exact  # noqa: PLC0415

    by_key = {r["key"]: r for _, r in con.iterrows()}
    g = by_key["glasses"]
    k, n = int(g["k"]), int(g["n"])
    lines = [
        header,
        f"% image-level deciles: {k} easiest vs {k} hardest images (of {n})",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        f"Trait (Color~FERET) & Easiest {k} & Hardest {k} & Ratio \\\\",
        "\\midrule",
    ]
    for key, lab in CONTRAST:
        e, h = _num(by_key[key]["easiest"]), _num(by_key[key]["hardest"])
        ratio = (h / e) if (e and np.isfinite(e) and e != 0) else float("nan")
        rr = "--" if not np.isfinite(ratio) else f"{ratio:.2f}$\\times$"
        lines.append(f"{lab} & {e:.3g} & {h:.3g} & {rr} \\\\")
    eg, hg = int(g["count_easiest"]), int(g["count_hardest"])
    _, pf = fisher_exact([[hg, k - hg], [eg, k - eg]])
    lines.append("\\midrule")
    lines.append(f"Glasses (count) & {eg}/{k} & {hg}/{k} & Fisher $p={pf:.2f}$ \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def predictors_figure(corr: pd.DataFrame, path: Path) -> None:
    """Horizontal bars of the Color FERET predictor correlations."""
    import matplotlib  # noqa: PLC0415

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt  # noqa: PLC0415

    by_key = {r["key"]: r for _, r in corr.iterrows()}
    items = []
    for key, lab in DESCRIPTORS + CF_ATTRIBUTES:
        v = _num(by_key[key].get("colorferet")) if key in by_key else float("nan")
        if np.isfinite(v):
            items.append((lab.replace("\\", ""), v))
    items.sort(key=lambda x: x[1])
    fig, ax = plt.subplots(figsize=(7.6, 0.42 * len(items) + 1))
    cols = ["#2FB8C9" if v >= 0 else "#C0563A" for _, v in items]
    ax.barh([n for n, _ in items], [v for _, v in items], color=cols)
    ax.axvline(0, color="k", lw=0.8)
    ax.set_xlabel(
        "Spearman $\\rho$ between image property and difficulty (1 - id-cos), 512 B"
    )
    ax.set_title("What makes a Color FERET crop hard to compress")
    ax.grid(axis="x", alpha=0.3)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=140, bbox_inches="tight")
    plt.close(fig)


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    src = ap.add_mutually_exclusive_group()
    src.add_argument(
        "--input-dir", default=None, help="default: OUTPUT_ROOT/difficulty"
    )
    src.add_argument(
        "--from-results",
        action="store_true",
        help="read the shipped paper results (results/difficulty)",
    )
    ap.add_argument("--tables-dir", default=None, help="default: OUTPUT_ROOT/tables")
    ap.add_argument("--figures-dir", default=None, help="default: OUTPUT_ROOT/figures")
    ap.add_argument("--no-figure", action="store_true")
    ap.add_argument(
        "--paper-header",
        action="store_true",
        help="use the comment line of the published tables (byte-identical output)",
    )
    args = ap.parse_args(argv)
    setup_logging()
    if args.from_results:
        in_dir = config.results_dir("difficulty")
    elif args.input_dir:
        in_dir = Path(args.input_dir)
    else:
        in_dir = config.output_dir("difficulty")
    header = PAPER_HEADER if args.paper_header else HEADER
    tdir = Path(args.tables_dir) if args.tables_dir else config.output_dir("tables")
    tdir.mkdir(parents=True, exist_ok=True)
    corr = pd.read_csv(in_dir / "difficulty_correlations.csv")
    (tdir / "difficulty_predictors.tex").write_text(predictors_table(corr, header))
    log.info("wrote %s", tdir / "difficulty_predictors.tex")
    con_csv = in_dir / "difficulty_contrast.csv"
    if con_csv.exists():
        (tdir / "difficulty_contrast.tex").write_text(
            contrast_table(pd.read_csv(con_csv), header)
        )
        log.info("wrote %s", tdir / "difficulty_contrast.tex")
    else:
        log.warning("skip difficulty_contrast.tex: %s is missing", con_csv)
    if not args.no_figure:
        fdir = (
            Path(args.figures_dir) if args.figures_dir else config.output_dir("figures")
        )
        predictors_figure(corr, fdir / "difficulty_predictors.png")
        log.info("wrote %s", fdir / "difficulty_predictors.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
